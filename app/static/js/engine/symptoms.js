/* Kidney Diet Log — symptoms log: the browser twin of app/symptoms.py (schema step 15).

   What it holds, and nothing more: the fixed list of symptoms, the three severities, the limits, the handbook's red
   flags (the exact lines app/symptoms.py shows, taken from handbook/docs/get-help-now.md), the API shape of a stored
   symptom, and the grouping the Trends list uses. The app records and shows symptoms; it never names a cause, a
   treatment or a dose, so there is nothing of the kind here.

   The demo API (js/mock/symptoms.js) and the views (js/views/symptoms.js) use this file. Pure functions, no DOM, no
   I/O. Tests: tests/data/symptoms_vectors.json (generated by tests/data/gen_symptoms_vectors.py from the server's own
   code) through `node tests/js/run_vectors.mjs`, and tests/test_symptoms_vectors.py.

   Exposes KH.symptomRules = { SYMPTOMS, KEYS, NAMES, SEVERITIES, SEVERITY_LABELS, MAX_LABEL, MAX_NOTE, MAX_PER_DAY,
   HREF, LINK_TEXT, RED_FLAGS, redFlag, rowToSymptom, summarise }. */
(() => {
  'use strict';
  const root = typeof window !== 'undefined' ? window : globalThis;
  const KH = root.KH || (root.KH = {});

  // [key, name shown] in the order the app lists them; "other" is named by the person's own label.
  const SYMPTOMS = [
    ['swelling', 'Swelling'],
    ['itching', 'Itching'],
    ['tiredness', 'Tiredness'],
    ['cramps', 'Cramps'],
    ['nausea', 'Nausea'],
    ['breathlessness', 'Breathlessness'],
    ['poor_appetite', 'Poor appetite'],
    ['other', 'Other'],
  ];
  const KEYS = SYMPTOMS.map((s) => s[0]);
  const NAMES = Object.fromEntries(SYMPTOMS);
  const SEVERITIES = [1, 2, 3];
  const SEVERITY_LABELS = { 1: 'Mild', 2: 'Moderate', 3: 'Severe' };
  const MAX_LABEL = 60; // app/models.py MAX_SYMPTOM_LABEL
  const MAX_NOTE = 300; // app/models.py MAX_SYMPTOM_NOTE
  const MAX_PER_DAY = 30; // app/models.py MAX_SYMPTOMS_PER_DAY

  const HREF = '/learn/get-help-now/';
  const LINK_TEXT = 'Get help now';
  // The symptoms the handbook's Get help now page sorts under "Call 911 now" (emergency) or "Call your care team today"
  // (today). Copied from app/symptoms.py RED_FLAGS; tests/test_symptoms.py checks the server's words against the page.
  const RED_FLAGS = {
    breathlessness: {
      level: 'emergency',
      text: 'The handbook lists “severe breathlessness” and “sudden breathlessness or fainting with no clear cause” '
        + 'under “Call 911 now”.',
    },
    swelling: {
      level: 'today',
      text: 'The handbook lists “new swelling of the legs, ankles or face” under “Call your care team today”.',
    },
  };

  // The handbook pointer for a symptom recorded at a severity, or null for a symptom the page does not list.
  function redFlag(symptom, severity) {
    if (!Object.prototype.hasOwnProperty.call(RED_FLAGS, symptom)) return null;
    const entry = RED_FLAGS[symptom];
    return { level: entry.level, text: entry.text, href: HREF, link_text: LINK_TEXT, prominent: severity === 3 };
  }

  // A stored row ({ id, date, symptom, label, severity, note, created_at }) → the API shape.
  function rowToSymptom(row) {
    const label = row.label || '';
    const severity = Number(row.severity);
    return {
      id: row.id,
      date: row.date,
      symptom: row.symptom,
      label,
      name: row.symptom === 'other' ? label : NAMES[row.symptom],
      severity,
      severity_label: SEVERITY_LABELS[severity],
      note: row.note || '',
      created_at: row.created_at,
      red_flag: redFlag(row.symptom, severity),
    };
  }

  // The Trends list: the API's symptoms (any order) → one group per symptom (an "other" per label, ignoring case), most
  // days first, then by name. Each group has `days` (oldest first, one { date, severity } per day, the highest severity
  // recorded that day), `dayCount`, `worst`, `worst_label` and the symptom's `red_flag` (as recorded at its worst).
  function summarise(symptoms) {
    const groups = new Map();
    for (const s of symptoms) {
      const key = s.symptom === 'other' ? `other:${s.label.toLowerCase()}` : s.symptom;
      let g = groups.get(key);
      if (!g) {
        g = { key, symptom: s.symptom, name: s.name, byDate: new Map(), worst: 0 };
        groups.set(key, g);
      }
      g.byDate.set(s.date, Math.max(g.byDate.get(s.date) || 0, s.severity));
      g.worst = Math.max(g.worst, s.severity);
    }
    const out = [];
    for (const g of groups.values()) {
      const days = [...g.byDate.entries()].map(([date, severity]) => ({ date, severity })).sort((a, b) => (a.date < b.date ? -1 : a.date > b.date ? 1 : 0));
      out.push({ key: g.key, symptom: g.symptom, name: g.name, days, dayCount: days.length, worst: g.worst,
        worst_label: SEVERITY_LABELS[g.worst], red_flag: redFlag(g.symptom, g.worst) });
    }
    out.sort((a, b) => (b.dayCount - a.dayCount) || (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
    return out;
  }

  KH.symptomRules = { SYMPTOMS, KEYS, NAMES, SEVERITIES, SEVERITY_LABELS, MAX_LABEL, MAX_NOTE, MAX_PER_DAY, HREF, LINK_TEXT, RED_FLAGS,
    redFlag, rowToSymptom, summarise };
})();
