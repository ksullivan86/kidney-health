/* Kidney Diet Log — the active-day calorie extra: the browser twin of app/activity.py (design note 28 §4.2).

   On a day with a Whoop figure and the setting on, the calorie target is the base target plus
     extra = min(ceiling, round-half-up-to-10(max(0, burned − quiet) × share% ÷ 100)),
   where "quiet" is the lower quartile (nearest rank) of Whoop's calories on the person's finished days in the 28 days before
   (at least 14 such days; fewer: no extra yet). Only calories rise. HRV, recovery, sleep and strain never change anything.
   Never insulin advice.

   Pure functions, no DOM, no I/O. Tests: tests/data/activity_vectors.json (generated by tests/data/gen_activity_vectors.py
   from the server's own code) through `node tests/js/run_vectors.mjs`.

   Exposes KH.activityRules = { QUIET_WINDOW_DAYS, QUIET_MIN_DAYS, QUIET_PERCENTILE, SHARE_DEFAULT, SHARE_MIN, SHARE_MAX,
   CEILING_MIN, CEILING_MAX, quietLevel, extraKcal, baseKcal, raised, calorieExtra }. */
(() => {
  'use strict';
  const root = typeof window !== 'undefined' ? window : globalThis;
  const KH = root.KH || (root.KH = {});

  const QUIET_WINDOW_DAYS = 28;
  const QUIET_MIN_DAYS = 14;
  const QUIET_PERCENTILE = 25;
  const SHARE_DEFAULT = 100;
  const SHARE_MIN = 10;
  const SHARE_MAX = 100;
  const CEILING_MIN = 50;
  const CEILING_MAX = 3000;

  const isNum = (v) => typeof v === 'number' && Number.isFinite(v);
  const whole = (v) => (isNum(v) && Number.isInteger(v) ? v : null);

  function quietLevel(history) {
    const values = (history || []).map(whole).filter((v) => v != null && v > 0).sort((a, b) => a - b);
    if (values.length < QUIET_MIN_DAYS) return null;
    const rank = Math.floor((QUIET_PERCENTILE * values.length + 99) / 100);
    return values[Math.max(rank, 1) - 1];
  }

  function extraKcal(burned, quiet, sharePct, ceilingKcal) {
    const above = Math.max(0, burned - quiet);
    const extra = Math.floor((above * sharePct + 500) / 1000) * 10;
    return ceilingKcal != null ? Math.min(extra, ceilingKcal) : extra;
  }

  function baseKcal(target) {
    if (target && typeof target === 'object') {
      for (const side of ['max', 'min']) if (isNum(target[side]) && target[side] > 0) return target[side];
      return null;
    }
    return isNum(target) && target > 0 ? target : null;
  }

  function raised(target, extra) {
    if (!extra) return target;
    if (target && typeof target === 'object') {
      return Object.fromEntries(Object.entries(target).map(([k, v]) => [k, isNum(v) ? v + extra : v]));
    }
    return target + extra;
  }

  function calorieExtra(setting, baseTarget, burned, history) {
    if (!setting || !setting.enabled) return null;
    const base = baseKcal(baseTarget);
    const kcal = whole(burned);
    if (base == null || kcal == null || kcal <= 0) return null;
    const days = (history || []).filter((h) => (whole(h) || 0) > 0);
    const quiet = quietLevel(days);
    const share = setting.share_pct || SHARE_DEFAULT;
    const ceiling = setting.ceiling_kcal == null ? null : setting.ceiling_kcal;
    const extra = quiet == null ? 0 : extraKcal(kcal, quiet, share, ceiling);
    return { base_kcal: base, extra_kcal: extra, burned_kcal: kcal, quiet_kcal: quiet, share_pct: share,
      ceiling_kcal: ceiling, history_days: days.length, source: 'whoop' };
  }

  KH.activityRules = { QUIET_WINDOW_DAYS, QUIET_MIN_DAYS, QUIET_PERCENTILE, SHARE_DEFAULT, SHARE_MIN, SHARE_MAX, CEILING_MIN,
    CEILING_MAX, quietLevel, extraKcal, baseKcal, raised, calorieExtra };
})();
