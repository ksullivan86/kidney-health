/* Kidney Diet Log — weight and blood pressure log: the browser twin of the pure part of app/body.py (schema step 18, note 10).

   What it holds, and nothing more: the units (kilograms and pounds, 0.45359237 exactly), the limits, the check of the latest weight
   against the person's weight-gain alarm, the 7-day blood pressure means against the person's goal, the change over six months, the
   handbook's own words for a warning sign (the exact lines app/body.py shows, taken from handbook/docs/get-help-now.md), the API
   shape of a stored row and the summary that Today shows. The alarm and the goal are the numbers the person's care team gave
   them: nothing here suggests either, and the app says nothing about a cause, a treatment or a medicine.

   The demo API (js/mock/body.js) and, in Part B, the views use this file. Pure functions, no DOM, no I/O. Tests:
   tests/data/body_vectors.json (generated by tests/data/gen_body_vectors.py from the server's own code) through
   `node tests/js/run_vectors.mjs`, and tests/test_body_vectors.py.

   Needs js/engine/rules.js first (KH.rules.halfUp: Decimal half-up on the shortest repr, as the server's nutrients._half_up).

   Exposes KH.bodyRules = { KG_PER_LB, WEIGHT_CONTEXTS, BLOOD_PRESSURE_CONTEXTS, SOURCES, UNITS, LIMITS, FLAG_SYSTOLIC, FLAG_DIASTOLIC,
   HREF, LINK_TEXT, RED_FLAGS, flagOf, bpFlag, roundKg, lbToKg, shownWeight, formatWeight, compareRows, shiftDay, daysBetween,
   weightAlarmCheck, bloodPressureWeek, sixMonthChange, summarise, rowToWeight, rowToReading }. */
(() => {
  'use strict';
  const root = typeof window !== 'undefined' ? window : globalThis;
  const KH = root.KH || (root.KH = {});
  const { halfUp } = KH.rules;

  const KG_PER_LB = 0.45359237; // exactly: the international pound (1959), NIST SP 811 Appendix B (note 10 F7)
  const WEIGHT_CONTEXTS = ['morning', 'before_dialysis', 'after_dialysis', 'other'];
  const BLOOD_PRESSURE_CONTEXTS = ['morning', 'evening', 'before_dialysis', 'after_dialysis', 'other'];
  const SOURCES = ['manual', 'apple_health', 'import', 'shortcut'];
  const UNITS = ['kg', 'lb'];
  // app/models.py: the project's own plausibility ranges (not clinical numbers) and the bounds on what one person can store.
  const LIMITS = {
    min_kg: 20, max_kg: 400, min_systolic: 50, max_systolic: 300, min_diastolic: 20, max_diastolic: 200, min_pulse: 20, max_pulse: 250,
    max_note: 200, max_weights_per_day: 20, max_readings_per_day: 30, max_batch: 1000, max_source_key: 64,
  };
  const FLAG_SYSTOLIC = 180; // NHLBI "180/120" (note 10 F5), read as a top number of 180 or more or a bottom number of 120 or more
  const FLAG_DIASTOLIC = 120;
  const WEEK_DAYS = 7;
  const MIN_READINGS_FOR_VERDICT = 3;
  const BETWEEN_SESSIONS_DAYS = 7;
  const SIX_MONTH_DAYS = 182;
  const SIX_MONTH_WINDOW_DAYS = 30;

  const CONTEXT_PHRASES = {
    morning: 'your morning weight',
    before_dialysis: 'your weight before dialysis',
    after_dialysis: 'your weight after dialysis',
    other: 'your other weight',
  };
  const NO_REFERENCE_BETWEEN_SESSIONS = 'Add a weight after a session to compare';
  const NO_REFERENCE_DAYS = 'Not enough weights to compare yet';

  // ---- the handbook's words (app/body.py RED_FLAGS; tests/test_body.py checks the server's words against the page)
  const HREF = '/learn/get-help-now/';
  const LINK_TEXT = 'Get help now';
  const TODAY = 'today';
  const EMERGENCY = 'emergency';
  const RED_FLAGS = {
    weight_alarm: {
      level: TODAY,
      text: 'The handbook lists “weight gain above the alarm number your team gave you” under “Call your care team today”.',
      prominent: false, // the person set the number
    },
    blood_pressure: {
      level: EMERGENCY,
      // The 911 signs come first: with one of them nobody should rest and measure again before calling (app/body.py).
      text: 'The handbook lists “a blood pressure of 180/120 or higher with a sudden severe headache, trouble breathing, '
        + 'sudden severe pain in the chest, belly or back, numbness or weakness, a sudden change in vision or problems '
        + 'talking” under “Call 911 now”. Without those signs, rest for 5 minutes and measure again: it lists “a blood '
        + 'pressure of 180/120 or higher that is still that high when you check again after resting 5 minutes” under '
        + '“Call your care team today”.',
      prominent: true,
    },
  };
  function flagOf(key) {
    const e = RED_FLAGS[key];
    return { level: e.level, text: e.text, href: HREF, link_text: LINK_TEXT, prominent: e.prominent };
  }
  // The handbook pointer for a reading at 180 top or 120 bottom or more, else null.
  function bpFlag(systolic, diastolic) {
    return systolic >= FLAG_SYSTOLIC || diastolic >= FLAG_DIASTOLIC ? flagOf('blood_pressure') : null;
  }

  // ---- units
  const roundKg = (kg) => halfUp(Number(kg), 2); // a weight as it is stored: kilograms, half up to 0.01 kg
  const lbToKg = (lb) => roundKg(Number(lb) * KG_PER_LB);
  // The number shown for a stored weight in `unit`: one decimal, half up (154.25 shows 154.3).
  const shownWeight = (kg, unit) => halfUp(unit === 'kg' ? Number(kg) : Number(kg) / KG_PER_LB, 1);
  const formatWeight = (kg, unit) => `${shownWeight(kg, unit).toFixed(1)} ${unit}`;

  // ---- days
  function dayMs(day) {
    const [y, m, d] = day.split('-').map(Number);
    return Date.UTC(y, m - 1, d);
  }
  const shiftDay = (day, days) => new Date(dayMs(day) + days * 86400000).toISOString().slice(0, 10);
  const daysBetween = (first, second) => Math.round((dayMs(second) - dayMs(first)) / 86400000);

  // List order: oldest day first, then by time (a row with no time last), then id.
  function compareRows(a, b) {
    if (a.date !== b.date) return a.date < b.date ? -1 : 1;
    const an = a.time == null ? 1 : 0, bn = b.time == null ? 1 : 0;
    if (an !== bn) return an - bn;
    const at = a.time || '', bt = b.time || '';
    if (at !== bt) return at < bt ? -1 : 1;
    return a.id - b.id;
  }

  // The latest of `weights` (oldest first, API shape) against the person's weight-gain alarm {amount_kg, over, days}, or null
  // with no weight or no alarm number (app/body.py weight_alarm_check).
  function weightAlarmCheck(weights, alarm, { dryWeightKg = null, unit = 'kg' } = {}) {
    const amount = alarm.amount_kg;
    if (amount == null || !weights.length) return null;
    const latest = weights[weights.length - 1];
    const earlier = weights.slice(0, -1);
    const over = alarm.over, days = Number(alarm.days);
    let reference = null, kind = null, referenceKg = null, noneMessage;
    if (over === 'between_sessions') {
      const floor = shiftDay(latest.date, -BETWEEN_SESSIONS_DAYS);
      const found = earlier.filter((w) => w.context === 'after_dialysis' && w.date >= floor);
      if (found.length) { reference = found[found.length - 1]; kind = 'after_dialysis'; referenceKg = reference.kg; } else if (dryWeightKg != null) {
        kind = 'dry_weight'; referenceKg = Number(dryWeightKg);
      }
      noneMessage = NO_REFERENCE_BETWEEN_SESSIONS;
    } else {
      const target = shiftDay(latest.date, -days), floor = shiftDay(latest.date, -2 * days);
      const found = earlier.filter((w) => w.context === latest.context && w.date >= floor && w.date <= target);
      if (found.length) { reference = found[found.length - 1]; kind = 'same_context'; referenceKg = reference.kg; }
      noneMessage = NO_REFERENCE_DAYS;
    }
    const out = { amount_kg: amount, over, days };
    if (kind == null || referenceKg == null) {
      return Object.assign(out, { status: 'no_reference', reference_kind: null, reference: null, reference_kg: null, gain_kg: null, over_alarm: null,
        message: noneMessage, flag: null });
    }
    const gain = roundKg(latest.kg - referenceKg);
    const overAlarm = gain > amount;
    const message = kind === 'dry_weight'
      ? `Compared with your dry weight in Profile (${formatWeight(referenceKg, unit)}).`
      : `Compared with ${CONTEXT_PHRASES[reference.context]} on ${reference.date} (${formatWeight(referenceKg, unit)}).`;
    return Object.assign(out, { status: 'compared', reference_kind: kind, reference, reference_kg: referenceKg, gain_kg: gain, over_alarm: overAlarm,
      message, flag: overAlarm ? flagOf('weight_alarm') : null });
  }

  // The readings dated `day` and the 6 days before it: how many, the mean top and bottom number (half up to whole numbers) and
  // whether a mean is at or above the goal; with fewer than 3 readings the means and `few: true`, no verdict.
  function bloodPressureWeek(readings, day, goal) {
    const floor = shiftDay(day, -(WEEK_DAYS - 1));
    const inside = readings.filter((r) => r.date >= floor && r.date <= day);
    const count = inside.length;
    const few = count < MIN_READINGS_FOR_VERDICT;
    let systolic = null, diastolic = null;
    if (count) {
      systolic = halfUp(inside.reduce((a, r) => a + r.systolic, 0) / count, 0);
      diastolic = halfUp(inside.reduce((a, r) => a + r.diastolic, 0) / count, 0);
    }
    const above = { systolic: null, diastolic: null };
    if (!few) {
      if (goal.systolic != null) above.systolic = systolic >= goal.systolic;
      if (goal.diastolic != null) above.diastolic = diastolic >= goal.diastolic;
    }
    const verdicts = [above.systolic, above.diastolic].filter((v) => v !== null);
    return { count, systolic, diastolic, few, above_goal: verdicts.length ? verdicts.some(Boolean) : null, above };
  }

  // The latest of `weights` (oldest first) against the weight dated closest to 182 days before it, within ±30 days (a tie goes to
  // the earlier day, then to the later weight of that day), or null.
  function sixMonthChange(weights) {
    if (!weights.length) return null;
    const latest = weights[weights.length - 1];
    const target = shiftDay(latest.date, -SIX_MONTH_DAYS);
    let best = null; // [distance, date, -index]
    weights.slice(0, -1).forEach((w, index) => {
      const distance = Math.abs(daysBetween(target, w.date));
      if (distance > SIX_MONTH_WINDOW_DAYS) return;
      const better = best === null || distance < best.d || (distance === best.d && (w.date < best.w.date || (w.date === best.w.date && index > best.i)));
      if (better) best = { d: distance, w, i: index };
    });
    if (best === null) return null;
    const earlier = best.w;
    return { latest, earlier, days: daysBetween(earlier.date, latest.date), change_kg: roundKg(latest.kg - earlier.kg),
      change_pct: halfUp((latest.kg - earlier.kg) / earlier.kg * 100, 1) };
  }

  // GET /api/body/summary?date= from API-shaped rows (any order; rows dated after `day` are ignored).
  function summarise(weights, readings, { day, units, alarm, goal, dryWeightKg = null }) {
    const ws = weights.filter((w) => w.date <= day).sort(compareRows);
    const rs = readings.filter((r) => r.date <= day).sort(compareRows);
    const latest = ws.length ? ws[ws.length - 1] : null;
    const previous = ws.length > 1 ? ws[ws.length - 2] : null;
    const gain = latest && previous ? { kg: roundKg(latest.kg - previous.kg), since: previous } : null;
    const flagged = rs.filter((r) => r.date === day && r.flag !== null);
    return {
      date: day,
      units,
      weight: { latest, previous, gain, alarm: weightAlarmCheck(ws, alarm, { dryWeightKg, unit: units }) },
      bp: { latest: rs.length ? rs[rs.length - 1] : null, week: bloodPressureWeek(rs, day, goal),
        goal: { systolic: goal.systolic == null ? null : goal.systolic, diastolic: goal.diastolic == null ? null : goal.diastolic },
        flagged_today: flagged.length ? flagged[flagged.length - 1] : null },
    };
  }

  // A stored row → the API shape (app/body.py row_to_weight / row_to_reading).
  function rowToWeight(row) {
    return { id: row.id, date: row.date, time: row.time == null ? null : row.time, kg: Number(row.kg), context: row.context, note: row.note || '',
      source: row.source, via: row.via == null ? null : row.via, created_at: row.created_at, updated_at: row.updated_at };
  }
  function rowToReading(row) {
    const systolic = Number(row.systolic), diastolic = Number(row.diastolic);
    return { id: row.id, date: row.date, time: row.time == null ? null : row.time, systolic, diastolic, pulse: row.pulse == null ? null : Number(row.pulse),
      context: row.context, note: row.note || '', source: row.source, via: row.via == null ? null : row.via, created_at: row.created_at,
      updated_at: row.updated_at, flag: bpFlag(systolic, diastolic) };
  }

  KH.bodyRules = { KG_PER_LB, WEIGHT_CONTEXTS, BLOOD_PRESSURE_CONTEXTS, SOURCES, UNITS, LIMITS, FLAG_SYSTOLIC, FLAG_DIASTOLIC, HREF, LINK_TEXT, RED_FLAGS,
    flagOf, bpFlag, roundKg, lbToKg, shownWeight, formatWeight, compareRows, shiftDay, daysBetween, weightAlarmCheck, bloodPressureWeek,
    sixMonthChange, summarise, rowToWeight, rowToReading };
})();
