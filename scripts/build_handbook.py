def nice_number(x: float) -> str:
    whole = int(x + 1e-9)
    frac = x - whole
    if frac < 0.02:
        return str(whole)
    if frac > 0.98:
        return str(whole + 1)
    for value, glyph in _FRACTIONS:
        if abs(frac - value) < 0.02:
            return (str(whole) if whole else "") + glyph
    return f"{x:.1f}".rstrip("0").rstrip(".")


def parse_qty(text: str) -> float:
    if "-" in text:
        whole, frac = text.split("-", 1)
        return float(whole) + parse_qty(frac)
    if "/" in text:
        num, den = text.split("/", 1)
        return float(num) / float(den)
    return float(text)


def amount_text(food: dict, servings: float) -> str:
    """Household amount for `servings` of `food` ("2½ oz cooked (71 g)", "1½ cups (237 g)")."""
    grams = float(food["serving_g"]) * servings
    g_txt = f"{int(half_up(grams)):,} g"
    category = food.get("category", "")
    m = _SERVING_RE.match(food["serving_desc"])
    if not m:
        return f"{nice_number(servings)} × {food['serving_desc']}"
    qty = parse_qty(m.group("qty"))
    rest = m.group("rest")
    unit, _, extra = rest.partition(",")
    unit, extra = unit.strip(), extra.strip()
    words = unit.split()
    is_egg = "egg" in food["name"].lower()
    if (category in ("Meat, Poultry & Eggs", "Fish & Seafood") and not is_egg) or unit == "oz":
        oz = round(grams / 28.3495 * 2) / 2
        return f"{nice_number(oz)} oz ({g_txt})"
    amount = qty * servings
    if words:
        last = words[-1]
        if amount > 1 + 1e-9 and last in _PLURAL:
            words[-1] = _PLURAL[last]
        elif amount <= 1 + 1e-9 and last in _SINGULAR:
            words[-1] = _SINGULAR[last]
    unit_txt = " ".join(words)
    keep_extra = extra and (abs(servings - 1) < 1e-9 or not re.search(r"\d", extra))
    text = f"{nice_number(amount)} {unit_txt}".strip()
    if keep_extra:
        text += f", {extra}"
    return f"{text} ({g_txt})"


