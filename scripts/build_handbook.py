def build_all() -> tuple[dict[Path, str], list[MenuResult], list[str]]:
    """Every generated file's content, the evaluated menus and any problems."""
    sources = load_sources()
    menus = load_yaml(MENUS_YML)
    foods = load_foods()
    rows = load_target_rows()
    person = menus["reference_person"]
    problems: list[str] = []
    h = float(person["height_cm"]) / 100
    bmi = float(person["weight_kg"]) / (h * h)
    if not (18.5 <= bmi <= 25):
        problems.append(f"reference person BMI {bmi:.1f} is outside 18.5–25; the reference weight would differ "
                        "from the actual weight (ARCHITECTURE.md 'Suggested targets')")
    last_checked = str(menus["last_checked"])
    results = [evaluate_menu(spec, foods, rows, person) for spec in menus["menus"]]
    for r in results:
        problems += r.problems
        for d in r.days:
            problems += [f"menu {r.spec['id']} {d.name}: {p}" for p in d.problems]
    for spec in menus["menus"]:
        for sid in spec["sources"]:
            if sid not in sources:
                problems.append(f"menu {spec['id']}: unknown source id {sid}")
    files = {
        HANDBOOK / "includes" / "sources.md": render_sources_include(sources),
        DOCS / "reference" / "sources.md": render_reference_sources(sources, last_checked),
        DOCS / "eat" / "_targets-table.md": render_targets_table(rows, float(person["weight_kg"])),
        DOCS / "eat" / "menus" / "_overview.md": render_menus_overview(results),
        DOCS / "eat" / "grocery-lists.md": render_grocery_lists(results, menus, last_checked),
    }
    for r in results:
        files[DOCS / "eat" / "menus" / f"{r.spec['id']}.md"] = render_menu_page(
            r, person, last_checked, menus.get("fact_checked"))
    recipe_files, _, recipe_problems = build_recipes(foods, sources)
    files.update(recipe_files)
    problems += recipe_problems
    return files, results, problems


def synced_assets() -> dict[Path, bytes]:
    """Assets copied from elsewhere: only present when their source is available here."""
    assets: dict[Path, bytes] = {}
    if APP_ICON.exists():
        assets[DOCS / "assets" / "icon.svg"] = APP_ICON.read_bytes()
    try:
        from importlib.metadata import distribution
        dist = distribution("mkdocs-material")
        # The theme's own licence, plus the licences of the two icon sets the site inlines
        # (mkdocs.yml: material/weather-* palette toggles, fontawesome/brands/github).
        wanted = {
            "LICENSE": "material-LICENSE.txt",                          # in *.dist-info
            "templates/.icons/material/LICENSE": "material-design-icons-LICENSE.txt",
            "templates/.icons/fontawesome/LICENSE.txt": "fontawesome-LICENSE.txt",
        }
        for f in dist.files or []:
            path = str(f).replace("\\", "/")
            for suffix, target in wanted.items():
                if suffix == "LICENSE":
                    match = f.name == "LICENSE" and ".dist-info" in path
                else:
                    match = path.endswith("material/" + suffix)
                if match:
                    assets[DOCS / "assets" / "licences" / target] = Path(dist.locate_file(f)).read_bytes()
    except Exception:  # mkdocs-material not installed: keep the committed copies
        pass
    return assets


def print_totals(results: list[MenuResult]) -> None:
    for r in results:
        lim = r.limits
        pl, ph = lim["protein_g"]
        print(f"\n== {r.spec['id']}: {r.spec['short_title']} ({r.targets.label}) ==")
        print(f"   limits: protein {pl:g}-{ph:.1f} g, K <= {lim['potassium_mg']}, P <= {lim['phosphorus_mg']}, "
              f"Na <= {lim['sodium_mg']}, fluid <= {lim['fluid_ml']}, kcal {lim['calories_kcal'][0]:.0f}-"
              f"{lim['calories_kcal'][1]:.0f}, main-meal carbs {lim['carbs_per_meal_g'][0]:g}-{lim['carbs_per_meal_g'][1]:g} g")
        print(f"   {'day':<34} {'kcal':>5} {'carb':>5} {'prot':>5} {'K':>5} {'P':>5} {'Na':>5} {'fluid':>5} {'fibre':>5}  meal carbs (B/L/D | snacks)  status")
        for d in r.days:
            t = d.totals
            mains = "/".join(fmt_int(m.totals["carbs_g"]) for m in d.meals if m.meal in MAIN_MEALS)
            snacks = ",".join(fmt_int(m.totals["carbs_g"]) for m in d.meals if m.meal == "snack")
            name = (d.name + (f" ({d.label})" if d.label else ""))[:34]
            status = "OK" if not d.problems else "FAIL: " + "; ".join(d.problems)
            print(f"   {name:<34} {t['calories_kcal']:5.0f} {t['carbs_g']:5.0f} {t['protein_g']:5.1f} "
                  f"{t['potassium_mg']:5.0f} {t['phosphorus_mg']:5.0f} {t['sodium_mg']:5.0f} {t['fluid_ml']:5.0f} "
                  f"{t['fiber_g']:5.1f}  {mains:<11} | {snacks:<10}  {status}")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="regenerate files (default)")
    mode.add_argument("--check", action="store_true", help="exit 1 if a generated file is stale or a menu fails")
    mode.add_argument("--totals", action="store_true", help="print menu day totals and checks; write nothing")
    args = ap.parse_args(argv)

    files, results, problems = build_all()
    if args.totals:
        print_totals(results)
        _, recipes, _ = build_recipes(load_foods(), load_sources())
        if recipes:
            print("\n== recipes (per serving) ==")
            print(f"   {'recipe':<40} {'kcal':>5} {'carb':>5} {'prot':>5} {'K':>5} {'P':>5} {'Na':>5} {'fluid':>5} {'fibre':>5}  status")
            for r in recipes:
                p = r.per_serving
                status = "OK" if not r.problems else "FAIL: " + "; ".join(r.problems)
                print(f"   {r.spec['id'][:40]:<40} {p['calories_kcal']:5.0f} {p['carbs_g']:5.1f} {p['protein_g']:5.1f} "
                      f"{p['potassium_mg']:5.0f} {p['phosphorus_mg']:5.0f} {p['sodium_mg']:5.0f} {p['fluid_ml']:5.0f} "
                      f"{p['fiber_g']:5.1f}  {status}")
        for p in problems:
            print("PROBLEM:", p)
        return 1 if problems else 0

    status = 0
    if problems:
        for p in problems:
            print("menu check failed:", p, file=sys.stderr)
        status = 1

    stale = []
    for path, content in files.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if args.check:
            stale.append(path)
            diff = difflib.unified_diff((current or "").splitlines(), content.splitlines(),
                                        f"{path.relative_to(ROOT)} (committed)", "(regenerated)", lineterm="", n=1)
            print("\n".join(list(diff)[:40]), file=sys.stderr)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print("wrote", path.relative_to(ROOT))
    for path, data in synced_assets().items():
        if path.exists() and path.read_bytes() == data:
            continue
        if args.check:
            print(f"warning: {path.relative_to(ROOT)} differs from its source; run scripts/build_handbook.py",
                  file=sys.stderr)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
            print("synced", path.relative_to(ROOT))
    if stale:
        print(f"{len(stale)} generated file(s) are stale: run python scripts/build_handbook.py", file=sys.stderr)
        status = 1
    if args.check and status == 0:
        print(f"handbook generated files are up to date ({len(files)} files, {len(results)} menus checked)")
    return status


if __name__ == "__main__":
    sys.exit(main())
