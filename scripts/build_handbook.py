def render_reference_sources(sources: dict, last_checked: str) -> str:
    meta = {
        "title": "Sources",
        "description": "Every source the handbook cites, with its link, licence and the date it was last checked.",
        "slug": "sources", "audience": ["clinician", "patient", "caregiver"], "applies_to": ["all"],
        "status": "draft", "reviewed_by": "", "reviewed_on": None, "last_checked": last_checked, "sources": [],
    }
    out = [front_matter(meta), MARKER, "", "# Sources", "",
           "Pages cite these by id, for example `[KDIGO 2024 CKD guideline][K24]`. The list is generated from "
           "`handbook/sources.yml`; to add or correct a source, edit that file "
           "(see [Building the handbook](../self-hosting/building-the-handbook.md)). "
           "**Licence** says what the handbook may do with each source: KDIGO guidelines are CC BY-NC-ND, so we "
           "cite and paraphrase them and never adapt their tables or figures; pages from kidney charities and "
           "dialysis providers are linked and paraphrased, never copied.", ""]
    for kind, title in KIND_TITLES:
        items = [(sid, e) for sid, e in sources.items() if e.get("kind") == kind]
        if not items:
            continue
        out += [f"## {title}", ""]
        for sid, e in items:
            extra = ""
            if e.get("also"):
                extra = " Also: " + ", ".join(f"<{u}>" for u in e["also"]) + "."
            dg = ""
            if e.get("dg"):
                dg = " Diet-guide source " + ", ".join(str(n) for n in e["dg"]) + "."
            note = f" *{e['note']}*" if e.get("note") else ""
            out.append(f"- **{sid}**: {e['cite']} <{e['url']}>{extra}  ")
            out.append(f"  Licence: {e['licence']}. Checked {e['checked']}.{dg}{note}")
        out.append("")
    unknown = [sid for sid, e in sources.items() if e.get("kind") not in dict(KIND_TITLES)]
    if unknown:
        raise SystemExit(f"sources.yml: unknown kind for {unknown}")
    return "\n".join(out)


