# ----------------------------------------------------------------------------- small helpers

def half_up(value: float, places: int = 0) -> float:
    q = Decimal(1).scaleb(-places)
    return float(Decimal(repr(value)).quantize(q, rounding=ROUND_HALF_UP))


def fmt_int(value: float) -> str:
    return f"{int(half_up(value)):,}"


def fmt_1(value: float) -> str:
    return f"{half_up(value, 1):.1f}"


def yaml_scalar(value: str) -> str:
    """Quote a front-matter string when YAML would otherwise misread it."""
    if value == "" or re.search(r"[:#'\"\[\]{},&*!|>%@`]", value) or value != value.strip():
        return json.dumps(value, ensure_ascii=False)
    return value


_ISO_DATE = re.compile(r"\d{4}-\d{2}-\d{2}")


def front_matter(meta: dict) -> str:
    lines = ["---"]
    for key, value in meta.items():
        if isinstance(value, list):
            lines.append(f"{key}: [{', '.join(str(v) for v in value)}]")
        elif value is None:
            lines.append(f"{key}: null")
        elif isinstance(value, bool):
            lines.append(f"{key}: {'true' if value else 'false'}")
        else:
            text = str(value)
            if not _ISO_DATE.fullmatch(text):
                text = yaml_scalar(text)
            lines.append(f"{key}: {text}")
    lines.append("---")
    return "\n".join(lines) + "\n"


def with_fact_check(meta: dict, fact_checked) -> dict:
    """Add ``fact_checked`` (the date of the last clinical fact-check, from the data file) after
    ``last_checked`` so generated pages carry the same front matter as hand-written ones."""
    if not fact_checked:
        return meta
    out: dict = {}
    for key, value in meta.items():
        out[key] = value
        if key == "last_checked":
            out["fact_checked"] = str(fact_checked)
    return out


def md_cell(text: str) -> str:
    return str(text).replace("|", "\\|")


# ----------------------------------------------------------------------------- data loading

def load_yaml(path: Path):
    with path.open(encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def load_sources(path: Path = SOURCES_YML) -> dict:
    data = load_yaml(path)
    if not isinstance(data, dict):
        raise SystemExit(f"{path}: expected a mapping of id -> entry")
    return {str(k): v for k, v in data.items()}


def load_foods(path: Path = FOODS_JSON) -> dict[int, dict]:
    data = json.loads(path.read_text(encoding="utf-8"))
    return {int(f["fdc_id"]): f for f in data["foods"]}


def load_target_rows(path: Path = TARGETS_JSON) -> list[dict]:
    return json.loads(path.read_text(encoding="utf-8"))


# ----------------------------------------------------------------------------- targets

@dataclass
class Targets:
    label: str
    protein_min_per_kg: float
    protein_max_per_kg: float
    protein_min_g: int
    protein_max_g: int
    potassium_mg: int | None
    phosphorus_mg: int | None
    sodium_mg: int | None
    fluid_ml: int | None
    kcal_per_kg: float
    calories_kcal: int
    carbs_g: int
    carbs_per_meal_g: int
    calcium_mg: int | None


def find_row(rows: list[dict], stage: str, dialysis: str) -> dict:
    for row in rows:
        if str(row["stage"]) == str(stage) and row["dialysis"] == dialysis:
            return row
    raise SystemExit(f"targets_by_stage.json has no row for stage {stage!r}, dialysis {dialysis!r}")


def targets_for(row: dict, weight_kg: float, diabetes: str = "type1") -> Targets:
    pmin, pmax = float(row["protein_g_per_kg_min"]), float(row["protein_g_per_kg_max"])
    if diabetes != "none" and row["dialysis"] == "none" and str(row["stage"]) in DIABETES_FLOOR_STAGES:
        pmin = max(pmin, 0.8)
        pmax = max(pmax, pmin)
    kcal = int(half_up(float(row["calories_kcal_per_kg"]) * weight_kg, -1))  # nearest 10, as note 05
    carbs = int(half_up(kcal * 0.45 / 4))
    per_meal = max(15, int(half_up(carbs / 4 / 5)) * 5)
    return Targets(
        label=STAGE_LABELS.get((str(row["stage"]), row["dialysis"]), f"{row['stage']} {row['dialysis']}"),
        protein_min_per_kg=pmin, protein_max_per_kg=pmax,
        protein_min_g=int(half_up(pmin * weight_kg)), protein_max_g=int(half_up(pmax * weight_kg)),
        potassium_mg=row.get("potassium_mg"), phosphorus_mg=row.get("phosphorus_mg"),
        sodium_mg=row.get("sodium_mg"), fluid_ml=row.get("fluid_ml"),
        kcal_per_kg=float(row["calories_kcal_per_kg"]), calories_kcal=kcal, carbs_g=carbs,
        carbs_per_meal_g=per_meal, calcium_mg=row.get("calcium_mg"))


def render_targets_table(rows: list[dict], weight_kg: float = 70.0) -> str:
    order = [("1", "none"), ("2", "none"), ("3a", "none"), ("3b", "none"), ("4", "none"), ("5", "none"),
             ("5", "hemodialysis"), ("5", "peritoneal")]
    out = [MARKER, "",
           f"| Stage | Protein per kg (for {weight_kg:g} kg) | Potassium mg ¹ | Phosphorus mg ² | Sodium mg | "
           f"Fluid mL | Energy per kg (for {weight_kg:g} kg) | Calcium mg ³ |",
           "|---|---|---|---|---|---|---|---|"]
    merged: list[tuple[str, Targets]] = []
    for key in order:
        t = targets_for(find_row(rows, *key), weight_kg)
        label = t.label
        if merged and key in {("2", "none")} and merged[-1][0] == "G1" and _same(merged[-1][1], t):
            merged[-1] = ("G1–G2", t)
            continue
        merged.append((label, t))
    for label, t in merged:
        if t.protein_min_g == t.protein_max_g:
            protein = f"{t.protein_min_per_kg:.1f} g/kg (about {t.protein_min_g} g)"
        else:
            protein = (f"{t.protein_min_per_kg:.1f}–{t.protein_max_per_kg:.1f} g/kg "
                       f"({t.protein_min_g}–{t.protein_max_g} g)")
        fluid = "no set limit" if t.fluid_ml is None else f"{t.fluid_ml:,} ⁴"
        out.append(f"| {label} | {protein} | {_lim(t.potassium_mg)} | {_lim(t.phosphorus_mg)} | "
                   f"< {t.sodium_mg:,} | {fluid} | {t.kcal_per_kg:g} kcal/kg (about {t.calories_kcal:,} kcal) | "
                   f"{_lim(t.calcium_mg)} |")
    out += [
        "",
        "¹ A **review ceiling**, not a prescription: only restrict potassium if your blood potassium is high; "
        "your care team sets the number. ",
        "² Used when blood phosphate runs high; phosphate additives count most (see the Phosphorus page). ",
        "³ Total from food, supplements and calcium-based binders. ",
        "⁴ Hemodialysis: 1,000 mL plus your measured urine output (1,500 mL assumes about 500 mL of urine). "
        "Peritoneal dialysis: set from your urine output and ultrafiltration.",
        "",
        "Protein: with diabetes, never below 0.8 g/kg before dialysis (ADA 2026 Rec 11.3; KDIGO 2022 and 2024). "
        "Without diabetes, KDOQI 2020 allows 0.6–0.8 g/kg only under close clinical supervision. "
        f"\"Per kg\" means per kg of a reference weight your team chooses; the {weight_kg:g} kg column is an example. "
        "Energy: KDOQI 2020 gives 25–35 kcal/kg; on peritoneal dialysis subtract the calories absorbed from the "
        "dialysis fluid (often 400 or more a day).",
        "",
    ]
    return "\n".join(out)


def _same(a: Targets, b: Targets) -> bool:
    return (a.protein_min_g, a.protein_max_g, a.potassium_mg, a.phosphorus_mg, a.sodium_mg, a.fluid_ml,
            a.calories_kcal, a.calcium_mg) == (b.protein_min_g, b.protein_max_g, b.potassium_mg, b.phosphorus_mg,
                                               b.sodium_mg, b.fluid_ml, b.calories_kcal, b.calcium_mg)


def _lim(value) -> str:
    return "–" if value is None else f"≤ {int(value):,}"


