def render_sources_include(sources: dict) -> str:
    lines = [MARKER, "<!-- Reference-link definitions for every id in handbook/sources.yml. -->", ""]
    for sid, entry in sources.items():
        title = str(entry.get("short") or entry["cite"]).replace('"', "'")
