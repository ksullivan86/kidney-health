def evaluate_menu(spec: dict, foods: dict[int, dict], rows: list[dict], person: dict) -> MenuResult:
    weight = float(person["weight_kg"])
    row = find_row(rows, str(spec["targets_row"]["stage"]), spec["targets_row"]["dialysis"])
    t = targets_for(row, weight, person.get("diabetes", "type1"))
    if spec.get("targets_label"):  # e.g. the transplant menu uses the stage 1-2 row
        t.label = str(spec["targets_label"])
    limits = menu_limits(spec, t, weight)
    unknown_rules = set(spec.get("rules", [])) - set(RULE_TEXT)
    if unknown_rules:
        raise SystemExit(f"menu {spec['id']}: unknown rules {sorted(unknown_rules)}")
    rules = set(spec.get("rules", []))
    result = MenuResult(spec=spec, targets=t, limits=limits, days=[])
    if len(spec.get("days", [])) != 7:
        result.problems.append(f"menu {spec['id']}: expected 7 days, found {len(spec.get('days', []))}")
    for day in spec.get("days", []):
        d = DayResult(name=day["name"], label=day.get("label", ""), note=day.get("note", ""),
                      dialysis_day=day.get("dialysis_day"), meals=[], totals=_zero())
        for meal in day["meals"]:
            mr = MealResult(meal=meal["meal"], label=meal.get("label") or MEAL_TITLES[meal["meal"]], items=[],
                            totals=_zero())
            if meal["meal"] not in MEAL_TITLES:
                d.problems.append(f"unknown meal {meal['meal']!r}")
            for item in meal["items"]:
                fdc = int(item["fdc_id"])
                food = foods.get(fdc)
                if food is None:
                    d.problems.append(f"fdc_id {fdc} is not in data/foods.json")
                    continue
                servings = float(item["servings"])
                if servings <= 0:
                    d.problems.append(f"{food['name']}: servings must be > 0")
                flags = set(food.get("flags", []))
                if "avoid_ckd" in flags:
                    d.problems.append(f"{food['name']} is flagged avoid_ckd")
                if "hypo_treatment" in flags:
                    d.problems.append(f"{food['name']} is a hypo treatment; keep rescue foods out of menus")
                if "no_phosphate_additive" in rules and "phosphate_additive" in flags:
                    d.problems.append(f"{food['name']} has a phosphate additive")
                if "no_grapefruit" in rules and any(w in food["name"].lower() for w in GRAPEFRUIT_WORDS):
                    d.problems.append(f"{food['name']}: no grapefruit or its relatives on this menu")
                if "transplant_food_safety" in rules and fdc in TRANSPLANT_UNSAFE:
                    d.problems.append(f"{food['name']} needs extra food-safety care after a transplant")
                tot = item_totals(food, servings)
                mr.items.append(ItemResult(food=food, servings=servings, note=item.get("note", ""), totals=tot))
                _add(mr.totals, tot)
            d.meals.append(mr)
            _add(d.totals, mr.totals)
        _check_day(d, limits)
        result.days.append(d)
    if spec.get("dialysis_days"):
        kinds = {d.dialysis_day for d in result.days}
        if kinds != {True, False}:
            result.problems.append(f"menu {spec['id']}: needs both dialysis-day and non-dialysis-day variants")
    return result


def _check_day(d: DayResult, limits: dict) -> None:
    tot = d.totals
    lo, hi = limits["protein_g"]
    if not (lo - 1e-9 <= tot["protein_g"] <= hi + 1e-9):
        d.problems.append(f"protein {tot['protein_g']:.1f} g outside {lo:g}–{hi:g}")
    for key in ("potassium_mg", "phosphorus_mg", "sodium_mg", "fluid_ml"):
        cap = limits.get(key)
        if cap is not None and tot[key] > cap + 1e-9:
            d.problems.append(f"{key} {tot[key]:.0f} over {cap}")
    lo, hi = limits["calories_kcal"]
    if not (lo <= tot["calories_kcal"] <= hi):
        d.problems.append(f"energy {tot['calories_kcal']:.0f} kcal outside {lo:.0f}–{hi:.0f}")
    fib = limits.get("fiber_per_1000_kcal")
    if fib and tot["fiber_g"] + 1e-9 < float(fib) * tot["calories_kcal"] / 1000:
        d.problems.append(f"fibre {tot['fiber_g']:.1f} g under {fib:g} g per 1,000 kcal "
                          f"({float(fib) * tot['calories_kcal'] / 1000:.1f} g)")
    clo, chi = limits["carbs_per_meal_g"]
    slo, shi = limits["snack_carbs_g"]
    seen = set()
    for m in d.meals:
        c = m.totals["carbs_g"]
        if m.meal in MAIN_MEALS:
            seen.add(m.meal)
            if not (clo - 1e-9 <= c <= chi + 1e-9):
                d.problems.append(f"{m.label} carbohydrate {c:.1f} g outside {clo:g}–{chi:g}")
        elif m.meal == "snack" and c > 0.5 and not (slo - 1e-9 <= c <= shi + 1e-9):
            # a drinks-only "snack" (water, tea) has no carbohydrate and needs no insulin plan
            d.problems.append(f"{m.label} carbohydrate {c:.1f} g outside {slo:g}–{shi:g}")
    missing = set(MAIN_MEALS) - seen
    if missing:
        d.problems.append(f"missing meals: {', '.join(sorted(missing))}")


def _fluid(v: float) -> str:
    return fmt_int(v) if v > 0.5 else "–"


