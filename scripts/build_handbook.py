@dataclass
class ItemResult:
    food: dict
    servings: float
    note: str
    totals: dict


@dataclass
class MealResult:
    meal: str
    label: str
    items: list[ItemResult]
    totals: dict


@dataclass
class DayResult:
    name: str
    label: str
    note: str
    dialysis_day: bool | None
    meals: list[MealResult]
    totals: dict
    problems: list[str] = field(default_factory=list)


@dataclass
class MenuResult:
    spec: dict
    targets: Targets
    limits: dict
    days: list[DayResult]
    problems: list[str] = field(default_factory=list)


def _zero() -> dict:
    return {k: 0.0 for k in NUTRIENTS}


def _add(acc: dict, other: dict) -> None:
    for k in NUTRIENTS:
        acc[k] += other.get(k, 0.0)


def item_totals(food: dict, servings: float) -> dict:
    n = food["nutrients"]
    return {k: float(n.get(k) or 0.0) * servings for k in NUTRIENTS}


def menu_limits(spec: dict, t: Targets, weight_kg: float) -> dict:
    """The numbers every day of this menu is checked against."""
    tol = float(spec.get("protein_about_tolerance_pct", 5)) / 100
    pmin = float(t.protein_min_g)
    pmax = float(t.protein_max_g)
    if t.protein_min_g == t.protein_max_g:  # "about X g/day" (note 05 §4.8): at least X, at most X + tol
        pmax = pmin * (1 + tol)
    energy = spec.get("energy_kcal") or [25 * weight_kg, 35 * weight_kg]
    per_meal = int(spec["carbs_per_meal_g"])
    meal_tol = float(spec.get("carb_tolerance_g", 10))
    if meal_tol > 10:
        raise SystemExit(f"menu {spec['id']}: carb_tolerance_g must be at most 10 (note 08 §4.5)")
    return {
        "protein_g": (pmin, pmax),
        "potassium_mg": t.potassium_mg if spec.get("potassium_limit", True) else None,
        "phosphorus_mg": t.phosphorus_mg if spec.get("phosphorus_limit", True) else None,
        "sodium_mg": t.sodium_mg,
        "fluid_ml": t.fluid_ml,
        "calories_kcal": (float(energy[0]), float(energy[1])),
        "carbs_per_meal_g": (per_meal - meal_tol, per_meal + meal_tol),
        "snack_carbs_g": tuple(spec.get("snack_carbs_g", [10, 30])),
        # ADA 2026 Rec 5.24: at least 14 g fibre per 1,000 kcal (used by the stage 1-2 menu)
        "fiber_per_1000_kcal": spec.get("fiber_min_per_1000_kcal"),
    }


