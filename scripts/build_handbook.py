#!/usr/bin/env python3
"""Generate the handbook's derived pages from the data the app uses, and check them.

Spec: docs/dev/research/08-handbook-site.md §4.5 and §5.5. Dev and CI only (runs in the handbook
venv: ``pip install --require-hashes -r handbook/requirements.lock``; needs PyYAML).

Usage
=====

    python scripts/build_handbook.py            # --write (default): regenerate every generated file
    python scripts/build_handbook.py --check    # regenerate in memory; exit 1 if a file is stale or a menu fails
    python scripts/build_handbook.py --totals   # print every menu day's totals and the checks, change nothing

Generated files (each starts with, or right after its front matter carries, the GENERATED marker):

* ``handbook/includes/sources.md``     reference-link definitions for every id in ``handbook/sources.yml``
  (appended to every page by pymdownx.snippets, so pages can write ``[KDIGO 2024][K24]``)
* ``handbook/docs/reference/sources.md``  the rendered bibliography
* ``handbook/docs/eat/_targets-table.md``  targets by stage, from ``docs/research/targets_by_stage.json``
* ``handbook/docs/eat/menus/<id>.md``   7-day sample menus, from ``handbook/data/menus.yml`` and the
  builtin foods in ``data/foods.json`` (by ``fdc_id`` and servings)
* ``handbook/docs/eat/menus/_overview.md``  the menu summary table included by ``eat/menus/index.md``
* ``handbook/docs/eat/grocery-lists.md``  printable weekly shopping checklists for every menu
* ``handbook/docs/eat/recipes/<id>.md``  original recipes with per-serving nutrients, from
  ``handbook/data/recipes.yml`` (ingredients by ``fdc_id`` and grams: builtin foods, plus a few SR Legacy
  seasonings whose per-100 g values are stored in that file)
* ``handbook/docs/eat/recipes/_overview.md``  the recipe table included by ``eat/recipes/index.md``

Synced assets (``--write`` copies them; ``--check`` only warns when they drift, because their sources
are owned elsewhere): ``docs/assets/icon.svg`` from ``app/static/icons/icon.svg`` when that file exists,
and ``docs/assets/licences/{material,material-design-icons,fontawesome}-LICENSE.txt`` from the installed
mkdocs-material distribution (the theme, and the two icon sets the site inlines).

Targets mirror ``app.nutrients.suggest_targets()`` for the reference person in ``menus.yml`` (70 kg,
170 cm, type 1 diabetes; BMI 24.2, so the reference weight is the actual weight): the stage row of
``targets_by_stage.json`` × weight, rounded half-up, with the ARCHITECTURE.md v0.3 item 10 diabetes
floor (protein never below 0.8 g/kg at G3a–G5 without dialysis). The script does not import ``app/``
so the handbook builds without the app's dependencies.
"""
