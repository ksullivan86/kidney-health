"""Parity vectors for the browser twin of entry versions and If-Match (ARCHITECTURE.md "Offline edits and deletes").

``tests/data/entry_version_vectors.json`` is generated by ``tests/data/gen_entry_version_vectors.py`` from the server's own
code (``app/log.py``) and replayed by ``node tests/js/run_vectors.mjs`` against the demo API (``app/static/js/mock/log.js``).
These tests fail when the committed file no longer matches the server (regenerate it, then make the twin agree), and check
what the vectors cover.
"""
from __future__ import annotations

import importlib.util
import json
import shutil
import subprocess
from pathlib import Path

import pytest

from app import log as food_log
from app.nutrients import NUTRIENT_KEYS

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "tests" / "data"


def generator():
    spec = importlib.util.spec_from_file_location("gen_entry_version_vectors", DATA / "gen_entry_version_vectors.py")
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def committed():
    return json.loads((DATA / "entry_version_vectors.json").read_text(encoding="utf-8"))


def test_vectors_are_current(committed):
    fresh = generator().build()
    assert committed == fresh, (
        "tests/data/entry_version_vectors.json is stale: app/log.py (entry_version, version_matches, PUT / DELETE) changed. Run "
        "`python3 tests/data/gen_entry_version_vectors.py`, then `node tests/js/run_vectors.mjs`, and update the browser twin "
        "(app/static/js/mock/log.js) until both agree."
    )


def test_the_fields_in_the_vectors_are_the_servers(committed):
    assert committed["fields"] == list(food_log.VERSION_FIELDS)
    assert all(set(case["entry"]) == {*food_log.VERSION_FIELDS, "nutrients"} for case in committed["cases"])
    assert all(set(case["entry"]["nutrients"]) == set(NUTRIENT_KEYS) for case in committed["cases"])


def test_the_vectors_cover_the_rule(committed):
    versions = [case["version"] for case in committed["cases"]]
    assert len(set(versions)) == len(versions) - 1  # "a whole amount as a float" and "as an integer" are the same content
    headers = {case["name"]: case["expected"] for case in committed["match_cases"]}
    assert headers["no header"] and headers["a star"] and not headers["a weak tag of the version"] and not headers["an empty header"]
    script = committed["script"]
    statuses = {s["answer"]["status"] for s in script if not s["answer"]["ok"]}
    assert statuses == {400, 404, 412}
    methods = {(s["method"], s["answer"]["ok"] or s["answer"]["status"]) for s in script if s["path"].startswith("/api/log/") and s["path"][9:].isdigit()}
    assert {("PUT", True), ("PUT", 412), ("DELETE", True), ("DELETE", 412), ("DELETE", 404), ("PUT", 404), ("PUT", 400)} <= methods
    # the 412 carries the entry as stored now, and a refused change leaves it as it was
    refused = [(i, s) for i, s in enumerate(script) if not s["answer"]["ok"] and s["answer"]["status"] == 412]
    assert refused and all(s["answer"]["current"]["version"] for _, s in refused)
    # an edit that is undone gives the first version again; a low treatment is edited and deleted like any other
    assert script[14]["answer"]["body"]["version"] == script[0]["answer"]["body"]["version"]
    assert script[25]["answer"]["body"]["purpose"] == "hypo" and script[26]["answer"] == {"ok": True, "body": None}


def test_the_node_runner_replays_the_entry_version_vectors():
    assert shutil.which("node"), "Node.js 22 is needed for the JS parity vectors (CLAUDE.md, Parity): install it and run again"
    proc = subprocess.run(["node", str(ROOT / "tests" / "js" / "run_vectors.mjs")], capture_output=True, text=True, timeout=120)
    assert proc.returncode == 0, proc.stdout + proc.stderr
    assert "entry version vectors:" in proc.stdout and "checks passed" in proc.stdout
