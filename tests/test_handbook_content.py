# ----------------------------------------------------------------------------- helpers

class _Loader(yaml.SafeLoader):
    """Safe loader that tolerates MkDocs tags (!ENV, !relative) in mkdocs.yml."""


def _tag(loader, suffix, node):  # pragma: no cover - trivial
    if isinstance(node, yaml.SequenceNode):
        return loader.construct_sequence(node)
    if isinstance(node, yaml.MappingNode):
        return loader.construct_mapping(node)
    return loader.construct_scalar(node)


_Loader.add_multi_constructor("!", _tag)


def _pages() -> list[Path]:
    return sorted(p for p in DOCS.rglob("*.md")
                  if not p.name.startswith("_") and "_drafts" not in p.parts)


def _rel(p: Path) -> str:
    return p.relative_to(DOCS).as_posix()


def _split(p: Path) -> tuple[dict, str]:
    text = p.read_text(encoding="utf-8")
    m = FRONT_MATTER.match(text)
    if not m:
        return {}, text
    return yaml.safe_load(m.group(1)) or {}, text[m.end():]


def _strip_code(text: str) -> str:
    text = re.sub(r"```.*?```", "", text, flags=re.S)
    return re.sub(r"`[^`\n]*`", "", text)


def _strip_comments(text: str) -> str:
    return re.sub(r"<!--.*?-->", "", text, flags=re.S)


def _cited(body: str) -> list[str]:
    return REF_LINK.findall(_strip_code(_strip_comments(body)))


def _sources() -> dict:
    data = yaml.safe_load(SOURCES_YML.read_text(encoding="utf-8"))
    return {str(k): v for k, v in data.items()}


def _is_medical(rel: str) -> bool:
    return rel.startswith(MEDICAL_DIRS) or rel in MEDICAL_PAGES


def _as_date(value):
    if isinstance(value, dt.date):
        return value
    if isinstance(value, str) and re.fullmatch(r"\d{4}-\d{2}-\d{2}", value):
        return dt.date.fromisoformat(value)
    return None


def _nav_files(node) -> list[str]:
    out: list[str] = []
    if isinstance(node, str):
        out.append(node)
    elif isinstance(node, list):
        for item in node:
            out += _nav_files(item)
    elif isinstance(node, dict):
        for value in node.values():
            out += _nav_files(value)
    return out


def _load_build_script():
    spec = importlib.util.spec_from_file_location("build_handbook", ROOT / "scripts" / "build_handbook.py")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module  # dataclasses resolve annotations through sys.modules
    spec.loader.exec_module(module)
    return module


