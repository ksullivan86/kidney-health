@pytest.mark.parametrize("page", PAGES, ids=PAGE_IDS)
def test_front_matter_schema(page):
    meta, body = _split(page)
    rel = _rel(page)
    assert meta, f"{rel}: missing YAML front matter"
    missing = [k for k in REQUIRED_KEYS if k not in meta]
    assert not missing, f"{rel}: front matter is missing {missing}"
    assert isinstance(meta["title"], str) and meta["title"].strip(), f"{rel}: empty title"
    assert isinstance(meta["description"], str) and len(meta["description"]) >= 20, f"{rel}: description too short"
    assert re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", str(meta["slug"])), f"{rel}: slug must be kebab-case"
    assert isinstance(meta["audience"], list) and meta["audience"], f"{rel}: audience must be a non-empty list"
    assert set(meta["audience"]) <= AUDIENCES, f"{rel}: unknown audience {set(meta['audience']) - AUDIENCES}"
    assert isinstance(meta["applies_to"], list) and meta["applies_to"], f"{rel}: applies_to must be a list"
    assert set(meta["applies_to"]) <= APPLIES_TO, f"{rel}: unknown applies_to {set(meta['applies_to']) - APPLIES_TO}"
    assert meta["status"] in STATUSES, f"{rel}: status must be draft or reviewed"
    assert _as_date(meta["last_checked"]), f"{rel}: last_checked must be an ISO date"
    assert isinstance(meta["sources"], list), f"{rel}: sources must be a list"
    if meta["status"] == "reviewed":
        assert str(meta.get("reviewed_by") or "").strip(), f"{rel}: a reviewed page needs reviewed_by"
        assert _as_date(meta.get("reviewed_on")), f"{rel}: a reviewed page needs reviewed_on (ISO date)"
    elif meta.get("reviewed_on") not in (None, ""):
        assert _as_date(meta["reviewed_on"]), f"{rel}: reviewed_on must be an ISO date or null"
    if "figures_as_of" in meta:
        assert _as_date(meta["figures_as_of"]), f"{rel}: figures_as_of must be an ISO date"
    h1 = re.search(r"^# (.+)$", body, re.M)
    assert h1, f"{rel}: needs an H1 heading"


def test_slugs_are_unique():
    seen: dict[str, str] = {}
    for page in PAGES:
        meta, _ = _split(page)
        slug = str(meta.get("slug"))
        assert slug not in seen, f"slug {slug!r} is used by {seen.get(slug)} and {_rel(page)}"
        seen[slug] = _rel(page)
        expected = page.parent.name if page.name == "index.md" else page.stem
        if page == DOCS / "index.md":
            expected = "start-here"
        elif page.parent == DOCS / "eat" / "menus" and page.name != "index.md":
            expected = f"menu-{page.stem}"  # menu-g1-g2 vs the stage page g1-g2
        expected = SLUG_EXCEPTIONS.get(_rel(page), expected)
        if slug != expected:
            warnings.warn(f"{_rel(page)}: slug {slug!r} differs from the file name {expected!r}")


