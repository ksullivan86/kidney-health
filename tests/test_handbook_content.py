@pytest.mark.parametrize("page", PAGES, ids=PAGE_IDS)
def test_every_cited_id_exists_and_is_listed(page):
    meta, body = _split(page)
    rel = _rel(page)
    known = {k.lower(): k for k in _sources()}
    listed = [str(s) for s in meta.get("sources") or []]
    for sid in listed:
        assert sid.lower() in known, f"{rel}: front matter cites unknown source id {sid!r}"
    cited = _cited(body)
    for sid in cited:
        assert sid.lower() in known, f"{rel}: body cites unknown source id [{sid}] (add it to handbook/sources.yml)"
    listed_lower = {s.lower() for s in listed}
    unlisted = sorted({s for s in cited if s.lower() not in listed_lower})
    assert not unlisted, f"{rel}: cited but not in front matter sources: {unlisted}"
    unused = sorted(set(listed) - {s for s in cited} - {known[s.lower()] for s in cited if s.lower() in known})
    if unused:
        warnings.warn(f"{rel}: listed in front matter but never cited: {unused}")


