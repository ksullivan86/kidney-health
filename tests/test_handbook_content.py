def _syllables(word: str) -> int:
    word = word.lower()
    groups = re.findall(r"[aeiouy]+", word)
    n = len(groups)
    if word.endswith("e") and n > 1 and not word.endswith(("le", "ee")):
        n -= 1
    return max(1, n)


def _fk_grade(text: str) -> float | None:
    text = _strip_code(_strip_comments(text))
    text = re.sub(r"^\s*\|.*$", "", text, flags=re.M)               # tables
    text = re.sub(r"^\s*(?:!!!|\?\?\?|===|--8<--).*$", "", text, flags=re.M)
    text = re.sub(r"\[([^\]]*)\]\[[^\]]*\]", r"\1", text)
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"[#*_>`-]", " ", text)
    sentences = [s for s in re.split(r"[.!?:;]+\s", text) if re.search(r"[A-Za-z]", s)]
    words = re.findall(r"[A-Za-z][A-Za-z']*", text)
    if len(words) < 80 or not sentences:
        return None
    syl = sum(_syllables(w) for w in words)
    return 0.39 * len(words) / len(sentences) + 11.8 * syl / len(words) - 15.59


def test_advisory_checks_only_warn():
    today = dt.date.today()
    hard_reading = []
    for page in PAGES:
        meta, body = _split(page)
        rel = _rel(page)
        last = _as_date(meta.get("reviewed_on")) or _as_date(meta.get("last_checked"))
        if last and (today - last).days > 365:
            warnings.warn(f"{rel}: last checked or reviewed {last}, over a year ago")
        figures = _as_date(meta.get("figures_as_of"))
        if figures and figures < dt.date(today.year, 1, 1):
            warnings.warn(f"{rel}: figures_as_of {figures} is from before this year")
        if "renal" in str(meta.get("title", "")).lower():
            warnings.warn(f"{rel}: use 'kidney' rather than 'renal' in titles (KDIGO nomenclature)")
        prose = REF_LINK.sub("]", _strip_code(_strip_comments(body)))
        if re.search(r"(?<!not )\bESRD\b", prose) and rel not in ESRD_OK:
            warnings.warn(f"{rel}: 'ESRD' outside living/costs-and-benefits (say 'kidney failure')")
        if {"patient", "caregiver"} & set(meta.get("audience") or []):
            grade = _fk_grade(body)
            if grade is not None and grade > 9:
                hard_reading.append(f"{rel} ({grade:.1f})")
    if hard_reading:
        warnings.warn("reading grade above 9 (aim for 8): " + ", ".join(hard_reading))
