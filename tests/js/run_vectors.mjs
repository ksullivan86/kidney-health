const GUIDANCE_ENGINE = ['app/static/js/engine/rules.js', ...GUIDANCE_PARTS.map((p) => `app/static/js/engine/guidance/${p}.js`)];
const GUIDANCE_VECTORS = join(ROOT, 'tests', 'data', 'guidance_vectors.json');
