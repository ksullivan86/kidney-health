// The replayer of tests/data/gen_guidance_vectors.py (context_from / call): plain JSON in, engine answer out.
function guidanceVectors(GE, file = GUIDANCE_VECTORS) {
  const doc = JSON.parse(readFileSync(file, 'utf8'));
  const own = file === GUIDANCE_VECTORS;
  const failures = [];
  let checks = 0;
  const expect = (label, got, want) => {
    checks += 1;
    if (!isDeepStrictEqual(plainSigned(got), want)) failures.push({ label, got: plainSigned(got), want });
  };
  if (own) {
    expect('rules_version', GE.R.RULES_VERSION, doc.rules_version);
    expect('rules_hash', GE.R.RULES_HASH, doc.rules_hash);
  }
  const REAL_ID0 = 101;
  const allFoods = new Map(doc.foods.map((r) => [r.id, GE.makeFood(r)]));
  const foodsFor = (inp) => {
    if (inp.food_set === 'all') return allFoods;
    const fixture = inp.food_set === 'fixture';
    return new Map([...allFoods].filter(([id]) => (id < REAL_ID0) === fixture));
  };
  const history = (rows, foods) => rows.map((h) => GE.historyEntry({ ...h, flags: foods.get(h.food_id).flags }));
  const contextFrom = (inp) => {
    const foods = foodsFor(inp);
    const day = inp.day.map((e) => GE.dayEntry({ id: e.id, meal: e.meal, status: e.status, food: foods.get(e.food_id), name: e.name,
      servings: e.servings, nutrients: { ...e.nutrients }, purpose: e.purpose }));
    const hist = history(inp.history, foods);
    return GE.makeContext({ date: inp.date, profile: inp.profile, prefs: inp.prefs, foods, day, history: hist,
      history60: inp.history60 != null ? history(inp.history60, foods) : null,
      saved_meals: inp.saved_meals.map((m) => ({ id: m.id, name: m.name, meal_hint: m.meal_hint, items: m.items.map(([f, q]) => [f, q]) })),
      combos: inp.combos.map((c) => ({ ...c, items: c.items.map(([f, q]) => [f, q]) })), tunables: inp.tunables });
  };
  const finite = (v) => (v === Infinity ? null : v);
  const call = (inp, spec) => {
    const fn = spec.fn;
    if (fn === 'prefilter') return GE.prefilter(spec.text, spec.dose_g == null ? GE.R.HYPO_DOSE_G : spec.dose_g);
    const ctx = contextFrom(inp);
    if (fn === 'period_insights') {
      return GE.periodInsights(ctx.profile, ctx.prefs, spec.start, spec.end, history(spec.entries, allFoods), history(spec.previous || [], allFoods));
    }
    if (fn === 'meal_room') {
      const room = GE.mealRoom(ctx, spec.meal, spec.open_meals || null);
      const dayLeft = {};
      for (const [k, v] of Object.entries(room.day_left)) dayLeft[k] = finite(v);
      return { open_meals: [...room.open_meals], room: GE.roomJson(room), meal_has: { ...room.meal_has }, meal_high_k: room.meal_high_k,
        day_high_k: room.day_high_k, usage_weight: { ...room.usage_weight }, day_left: dayLeft };
    }
    if (fn === 'what_fits') return GE.whatFits(ctx, spec.meal, spec.limit == null ? GE.R.DEFAULT_LIMIT : spec.limit, !!spec.explain);
    if (fn === 'find_swaps') return GE.findSwaps(ctx, spec.meal, ctx.foods.get(spec.food_id), spec.servings, spec.purpose || null, GE.R.SWAP_MAX, !!spec.explain);
    if (fn === 'hypo_options') return GE.hypoOptions(ctx);
    if (fn === 'plan_day') {
      return GE.planDay(ctx, spec.meals || null, { useSavedMeals: spec.use_saved_meals !== false, useUsual: spec.use_usual !== false,
        useStarters: spec.use_starters !== false, variant: spec.variant || 0 });
    }
    if (fn === 'day_insights') return GE.dayInsights(ctx);
    throw new Error(`unknown fn ${fn}`);
  };
  const counts = {};
  for (const c of doc.cases) {
    counts[c.call.fn] = (counts[c.call.fn] || 0) + 1;
    let got;
    try { got = call(c.input, c.call); } catch (e) { got = { exception: String(e && e.stack || e) }; }
    expect(`${c.id} (${c.call.fn})`, got, c.output);
  }
  return [checks, failures, `${doc.cases.length} cases: ${Object.entries(counts).map(([k, v]) => `${v} ${k}`).join(', ')}`];
}

