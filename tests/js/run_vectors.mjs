// The replayer of tests/data/gen_guidance_vectors.py (context_from / call): plain JSON in, engine answer out.
function guidanceVectors(GE, file = GUIDANCE_VECTORS) {
  const doc = JSON.parse(readFileSync(file, 'utf8'));
  const own = file === GUIDANCE_VECTORS;
  const failures = [];
  let checks = 0;
  const expect = (label, got, want) => {
    checks += 1;
    if (!isDeepStrictEqual(plainSigned(got), want)) failures.push({ label, got: plainSigned(got), want });
  };
  if (own) {
    expect('rules_version', GE.R.RULES_VERSION, doc.rules_version);
    expect('rules_hash', GE.R.RULES_HASH, doc.rules_hash);
  }
  const REAL_ID0 = 101;
  const allFoods = new Map(doc.foods.map((r) => [r.id, GE.makeFood(r)]));
  const foodsFor = (inp) => {
    if (inp.food_set === 'all') return allFoods;
    const fixture = inp.food_set === 'fixture';
    return new Map([...allFoods].filter(([id]) => (id < REAL_ID0) === fixture));
  };
  const history = (rows, foods) => rows.map((h) => GE.historyEntry({ ...h, flags: foods.get(h.food_id).flags }));
  const contextFrom = (inp) => {
    const foods = foodsFor(inp);
    const day = inp.day.map((e) => GE.dayEntry({ id: e.id, meal: e.meal, status: e.status, food: foods.get(e.food_id), name: e.name,
      servings: e.servings, nutrients: { ...e.nutrients }, purpose: e.purpose }));
    const hist = history(inp.history, foods);
    return GE.makeContext({ date: inp.date, profile: inp.profile, prefs: inp.prefs, foods, day, history: hist,
      history60: inp.history60 != null ? history(inp.history60, foods) : null,
      saved_meals: inp.saved_meals.map((m) => ({ id: m.id, name: m.name, meal_hint: m.meal_hint, items: m.items.map(([f, q]) => [f, q]) })),
      combos: inp.combos.map((c) => ({ ...c, items: c.items.map(([f, q]) => [f, q]) })), tunables: inp.tunables });
  };
  const finite = (v) => (v === Infinity ? null : v);
  const call = (inp, spec) => {
    const fn = spec.fn;
    if (fn === 'prefilter') return GE.prefilter(spec.text, spec.dose_g == null ? GE.R.HYPO_DOSE_G : spec.dose_g);
    const ctx = contextFrom(inp);
    if (fn === 'period_insights') {
      return GE.periodInsights(ctx.profile, ctx.prefs, spec.start, spec.end, history(spec.entries, allFoods), history(spec.previous || [], allFoods));
    }
    if (fn === 'meal_room') {
      const room = GE.mealRoom(ctx, spec.meal, spec.open_meals || null);
      const dayLeft = {};
      for (const [k, v] of Object.entries(room.day_left)) dayLeft[k] = finite(v);
      return { open_meals: [...room.open_meals], room: GE.roomJson(room), meal_has: { ...room.meal_has }, meal_high_k: room.meal_high_k,
        day_high_k: room.day_high_k, usage_weight: { ...room.usage_weight }, day_left: dayLeft };
    }
    if (fn === 'what_fits') return GE.whatFits(ctx, spec.meal, spec.limit == null ? GE.R.DEFAULT_LIMIT : spec.limit, !!spec.explain);
    if (fn === 'find_swaps') return GE.findSwaps(ctx, spec.meal, ctx.foods.get(spec.food_id), spec.servings, spec.purpose || null, GE.R.SWAP_MAX, !!spec.explain);
    if (fn === 'hypo_options') return GE.hypoOptions(ctx);
    if (fn === 'plan_day') {
      return GE.planDay(ctx, spec.meals || null, { useSavedMeals: spec.use_saved_meals !== false, useUsual: spec.use_usual !== false,
        useStarters: spec.use_starters !== false, variant: spec.variant || 0 });
    }
    if (fn === 'day_insights') return GE.dayInsights(ctx);
    throw new Error(`unknown fn ${fn}`);
  };
  const counts = {};
  for (const c of doc.cases) {
    counts[c.call.fn] = (counts[c.call.fn] || 0) + 1;
    let got;
    try { got = call(c.input, c.call); } catch (e) { got = { exception: String(e && e.stack || e) }; }
    expect(`${c.id} (${c.call.fn})`, got, c.output);
  }
  return [checks, failures, `${doc.cases.length} cases: ${Object.entries(counts).map(([k, v]) => `${v} ${k}`).join(', ')}`];
}

function loadBarcode() {
  const context = vm.createContext({ console, URL });
  vm.runInContext('globalThis.window = globalThis;', context);
  for (const rel of [...BARCODE_ENGINE, ...BARCODE_MOCK]) vm.runInContext(readFileSync(join(ROOT, rel), 'utf8'), context, { filename: rel });
  const KH = vm.runInContext('globalThis.KH', context);
  for (const part of ['gtin', 'textclean', 'additives', 'off', 'mock']) if (!KH[part]) throw new Error(`barcode twins did not define KH.${part}`);
  return KH;
}

// A demo API with only the tables the barcode route reads, signed in as person 1 who agreed to Open Food Facts.
function barcodeMock(KH) {
  const api = Object.create(KH.mock.MockApi.prototype);
  Object.assign(api, { _lastUs: 0, _foods: [], _foodById: new Map(), _nextFoodId: 1, _entries: [], _templates: [] });
  const settings = { 'food.off_enabled': true, 'food.off_consent': true, 'food.usda_branded_barcode': true };
  api._currentUser = () => ({ id: 1 });
  api._effectiveSetting = (key) => ({ value: settings[key] });
  return api;
}

function barcodeVectors(KH) {
  const doc = JSON.parse(readFileSync(BARCODE_VECTORS, 'utf8'));
  const failures = [];
  let checks = 0;
  const expect = (label, got, want) => {
    checks += 1;
    if (!isDeepStrictEqual(plain(got), want)) failures.push({ label, got: plain(got), want });
  };
  const G = KH.gtin;
  for (const c of doc.check_digit_cases) expect(`check_digit(${c.body})`, G.checkDigit(c.body), c.digit);
  for (const c of doc.gtin_cases) {
    let got;
    try {
      const g14 = G.normalize(c.code, c.format);
      got = { code: c.code, format: c.format, normalize: g14, classify: G.classify(g14), off_code: G.offCode(g14), usda_candidates: G.usdaCandidates(g14) };
    } catch (e) {
      got = e instanceof G.GtinError ? { code: c.code, format: c.format, error: { reason: e.reason, message: e.message } } : { exception: String(e) };
    }
    expect(`gtin ${JSON.stringify(c.code)} ${c.format}`, got, c);
  }
  for (const c of doc.textclean_cases) {
    expect(`clean_text(${JSON.stringify(c.value)}, ${c.max_len}, ${c.keep_newlines})`,
      KH.textclean.cleanText(c.value, { maxLen: c.max_len, keepNewlines: c.keep_newlines }), c.result);
  }
  for (const c of doc.additive_cases) {
    let got;
    try { got = KH.additives.scan(c.tags, c.text, c.name); } catch (e) { got = { exception: String(e && e.stack || e) }; }
    expect(`scan(${JSON.stringify(c.tags)}, ${JSON.stringify(c.text).slice(0, 80)}, ${JSON.stringify(c.name)})`, got, c.result);
  }
  for (const c of doc.quality_cases) expect(`quality_items(${JSON.stringify(c.codes)})`, KH.off.qualityItems(c.codes), c.items);
  // The demo's embedded rows are the generated ones (tests/test_barcode_vectors.py checks the file too).
  expect('js/mock/barcode.js DEMO_PRODUCTS', KH.mock.DEMO_PRODUCTS,
    doc.demo_products.map((p) => ({ fixture: p.fixture, code: p.code, format: p.format, row: p.row })));
  const api = barcodeMock(KH);
  for (const p of doc.demo_products) {
    let got;
    try { got = api.handle('POST', '/api/foods/barcode', { code: p.code, format: p.format }); delete got.food.id; } catch (e) {
      got = { exception: String(e && (e.detail || e.stack) || e) };
    }
    expect(`demo POST /api/foods/barcode ${p.fixture}`, got, p.result);
  }
  const summary = `${doc.gtin_cases.length} GTIN, ${doc.textclean_cases.length} text, ${doc.additive_cases.length} additive, `
    + `${doc.quality_cases.length} quality cases, ${doc.demo_products.length} demo products`;
  return [checks, failures, summary];
}

function report(name, file, [checks, failures, summary]) {
  if (failures.length) {
    for (const f of failures.slice(0, 20)) console.error(`MISMATCH ${f.label}\n   js:     ${JSON.stringify(f.got)}\n   python: ${JSON.stringify(f.want)}`);
    console.error(`\n${failures.length} of ${checks} checks failed (${file})`);
    return 1;
  }
  console.log(`${name} vectors: ${checks} checks passed (${summary})`);
  return 0;
}

function main() {
  const gi = process.argv.indexOf('--guidance');
  if (gi >= 0) {
    const file = process.argv[gi + 1];
    if (!file) { console.error('--guidance needs a file'); return 2; }
    return report('guidance', file, guidanceVectors(loadGuidance(), file));
  }
  const rules = loadEngine();
  const doc = JSON.parse(readFileSync(VECTORS, 'utf8'));
  const keys = doc.nutrient_keys;
  if (!isDeepStrictEqual(keys, plain(rules.NUTRIENT_KEYS))) {
    console.error(`nutrient keys differ: vectors ${keys} engine ${rules.NUTRIENT_KEYS}`);
    return 1;
  }
  const failures = [];
  let checks = 0;
  const expect = (label, got, want) => {
    checks += 1;
    if (!isDeepStrictEqual(plain(got), want)) failures.push({ label, got: plain(got), want });
  };

  for (const c of doc.food_cases) {
    const f = doc.foods[c.food];
    const scaled = Object.fromEntries(keys.map((k) => [k, f.nutrients[k] == null ? null : Number(f.nutrients[k]) * c.servings]));
    const label = `${f.name} x${c.servings} (${c.scope})`;
    const warnings = rules.evaluateWarnings(scaled, f.flags, f.kidney_notes, c.scope);
    expect(`${label}: warnings`, warnings, c.warnings);
    expect(`${label}: kidney_rating`, rules.ratingFromWarnings(warnings), c.kidney_rating);
    const rounded = rules.roundNutrients(scaled);
    expect(`${label}: rounded`, keys.map((k) => rounded[k]), c.rounded);
  }
  doc.boundary_cases.forEach((c, i) => {
    const label = `boundary ${i} ${JSON.stringify(c.nutrients)} ${JSON.stringify(c.flags)} (${c.scope})`;
    const warnings = rules.evaluateWarnings(c.nutrients, c.flags, c.kidney_notes, c.scope);
    expect(`${label}: warnings`, warnings, c.warnings);
    expect(`${label}: kidney_rating`, rules.ratingFromWarnings(warnings), c.kidney_rating);
  });
  for (const c of doc.round_cases) expect(`round_value(${c.key}, ${c.value})`, rules.roundValue(c.key, c.value), c.expected);

  const [sChecks, sFailures, sDoc] = settingsVectors();
  let status = 0;
  if (failures.length) {
    for (const f of failures.slice(0, 20)) console.error(`MISMATCH ${f.label}\n   js:     ${JSON.stringify(f.got)}\n   python: ${JSON.stringify(f.want)}`);
    console.error(`\n${failures.length} of ${checks} checks failed (tests/data/rules_vectors.json vs app/static/js/engine/rules.js)`);
    status = 1;
  } else {
    console.log(`rules vectors: ${checks} checks passed (${doc.food_cases.length} food cases, ${doc.boundary_cases.length} boundary cases, ${doc.round_cases.length} rounding cases)`);
  }
  if (sFailures.length) {
    for (const f of sFailures.slice(0, 20)) console.error(`MISMATCH ${f.label}\n   js:     ${JSON.stringify(f.got)}\n   python: ${JSON.stringify(f.want)}`);
    console.error(`\n${sFailures.length} of ${sChecks} checks failed (tests/data/settings_vectors.json vs ${SETTINGS_ENGINE})`);
    status = 1;
  } else {
    console.log(`settings vectors: ${sChecks} checks passed (${sDoc.registry.length} keys, ${sDoc.validation_cases.length} validation cases, ${sDoc.precedence_cases.length} precedence cases)`);
  }
  const targetsKH = loadTargets();
  status |= report('targets', 'tests/data/targets_vectors.json vs app/static/js/engine/targets.js', targetsVectors(targetsKH));
  status |= report('kidney function', 'tests/data/kidney_function_vectors.json vs app/static/js/engine/kidney_function.js', kidneyVectors(targetsKH));
  status |= report('guidance', 'tests/data/guidance_vectors.json vs app/static/js/engine/guidance/*.js', guidanceVectors(loadGuidance()));
  status |= report('barcode', 'tests/data/barcode_vectors.json vs app/static/js/engine/{gtin,textclean,additives,off}.js + js/mock/barcode.js', barcodeVectors(loadBarcode()));
  return status;
}

process.exitCode = main();
