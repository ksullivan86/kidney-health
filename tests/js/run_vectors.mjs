// Returns [checks, failures].
function settingsVectors() {
  const S = loadSettings();
  const doc = JSON.parse(readFileSync(SETTINGS_VECTORS, 'utf8'));
  const failures = [];
  let checks = 0;
  const expect = (label, got, want) => {
    checks += 1;
    if (!isDeepStrictEqual(plain(got), want)) failures.push({ label, got: plain(got), want });
  };
  // Registry: the same keys in the same order, each with the same description.
  expect('settings registry keys', S.DEFS.map((d) => d.key), doc.registry.map((r) => r.key));
  for (const want of doc.registry) {
    const def = S.BY_KEY[want.key];
    if (!def) { failures.push({ label: `registry ${want.key}`, got: null, want }); checks += 1; continue; }
    const got = {};
    for (const k of Object.keys(want)) got[k] = def[k] === undefined ? null : def[k];
    expect(`registry ${want.key}`, got, want);
  }
  for (const c of doc.validation_cases) {
    const def = S.BY_KEY[c.key];
    if (!def) continue;
    const r = S.validate(def, c.input);
    expect(`validate ${c.key} ${JSON.stringify(c.input)}`, r.error !== undefined ? { error: r.error } : { value: r.value },
      c.error !== undefined ? { error: c.error } : { value: c.value });
  }
  for (const c of doc.precedence_cases) {
    const ctx = { env: c.env, instance: c.instance, user: c.user };
    expect(`precedence "${c.name}": user view`, S.userView(ctx), c.user_view);
    expect(`precedence "${c.name}": admin view`, S.adminView(ctx), c.admin_view);
  }
  return [checks, failures, doc];
}

