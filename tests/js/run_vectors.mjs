const VECTORS = join(ROOT, 'tests', 'data', 'rules_vectors.json');
const SETTINGS_ENGINE = 'app/static/js/engine/settings.js';
const SETTINGS_VECTORS = join(ROOT, 'tests', 'data', 'settings_vectors.json');
const TARGETS_ENGINE = ['app/static/js/engine/rules.js', 'app/static/js/engine/kidney_function.js', 'app/static/js/engine/targets.js'];
const TARGETS_VECTORS = join(ROOT, 'tests', 'data', 'targets_vectors.json');
const KIDNEY_VECTORS = join(ROOT, 'tests', 'data', 'kidney_function_vectors.json');
