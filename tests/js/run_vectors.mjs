// Import: the edits of a step are applied to a copy of the base file exactly as tests/data/gen_import_vectors.py apply_edits does.
function applyEdits(doc, edits) {
  let out = doc;
  for (const e of edits) {
    if (e.op === 'replace') { out = JSON.parse(JSON.stringify(e.value)); continue; }
    let node = out;
    for (const part of e.path.slice(0, -1)) node = node[part];
    const last = e.path[e.path.length - 1];
    if (e.op === 'delete') { if (Array.isArray(node)) node.splice(last, 1); else delete node[last]; } else node[last] = JSON.parse(JSON.stringify(e.value));
  }
  return out;
}
