const closeTo = (a, b) => typeof a === 'number' && typeof b === 'number' && Math.abs(a - b) <= 1e-9 * Math.max(1, Math.abs(b));

// Returns [checks, failures, summary].
function targetsVectors(KH) {
  const T = KH.targets;
  const doc = JSON.parse(readFileSync(TARGETS_VECTORS, 'utf8'));
  const failures = [];
  let checks = 0;
  const expect = (label, got, want) => {
    checks += 1;
    if (!isDeepStrictEqual(plain(got), want)) failures.push({ label, got: plain(got), want });
  };
  const tables = T.tables();
  for (const name of Object.keys(doc.tables)) expect(`tables.${name}`, tables[name], doc.tables[name]);
  expect('table names', Object.keys(tables).sort(), Object.keys(doc.tables).sort());
  for (const c of doc.reference_weight_cases) {
    const r = T.referenceWeight(c.weight_kg, c.height_cm);
    expect(`reference_weight(${c.weight_kg}, ${c.height_cm})`, { weight_kg: r.weight_kg, basis: r.basis }, c.expect);
  }
  for (const c of doc.eer_cases) {
    checks += 1;
    const got = T.eerKcal(c.sex, c.activity, c.age, c.height_cm, c.weight_kg);
    if (!closeTo(got, c.kcal)) failures.push({ label: `eer ${c.sex} ${c.activity} ${c.age}`, got, want: c.kcal });
  }
  // The API returns {id, ...rules[key]} with id "P-2" for the keys "P-2d" and "P-2n"; the vectors keep the key.
  const catalogueKey = (rule) => {
    const { id, ...rest } = rule;
    const keys = id === 'P-2' ? ['P-2d', 'P-2n'] : [id];
    return keys.find((k) => isDeepStrictEqual(plain(rest), plain(T.RULES[k]))) || `${id} (not in the catalogue)`;
  };
  for (const c of doc.cases) {
    let got;
    try {
      got = T.suggestFromRecords(c.profile, c.labs, c.today, c.settings);
      got = { ...got, rules: got.rules.map(catalogueKey) };
    } catch (e) {
      if (e instanceof T.OutOfScope) got = { error: { code: e.code, message: e.message } };
      else if (e instanceof T.InvalidInput) got = { invalid: e.message };
      else got = { exception: String(e && e.stack || e) };
    }
    const want = c.expect;
    if ('targets' in want && 'targets' in got) {
      for (const k of Object.keys(want)) expect(`${c.id}: ${k}`, got[k], want[k]);
      expect(`${c.id}: keys`, Object.keys(got).sort(), Object.keys(want).sort());
    } else expect(`${c.id}`, got, want);
  }
  for (const c of doc.wrapper_cases) expect(`suggest_targets(${c.args.map((a) => JSON.stringify(a)).join(', ')})`, T.suggestTargets(...c.args), c.expect);
  return [checks, failures, `${doc.cases.length} cases, ${doc.wrapper_cases.length} wrapper cases, ${doc.eer_cases.length} EER cases`];
}

function kidneyVectors(KH) {
  const KF = KH.kidney;
  const doc = JSON.parse(readFileSync(KIDNEY_VECTORS, 'utf8'));
  const failures = [];
  let checks = 0;
  const expect = (label, got, want) => {
    checks += 1;
    if (!isDeepStrictEqual(plain(got), want)) failures.push({ label, got: plain(got), want });
  };
  expect('unit_table', KF.unitTable(), doc.unit_table);
  expect('unit_systems', KF.UNIT_SYSTEMS, doc.unit_systems);
  for (const c of doc.conversion_cases) {
    const value = c.value === 'Infinity' ? Infinity : c.value;
    let got;
    try { got = KF.convert(c.analyte, value, c.unit); } catch (e) { got = e instanceof KF.UnitError ? { error: e.message } : { exception: String(e) }; }
    expect(`convert(${c.analyte}, ${c.value}, ${c.unit})`, got, c.expect);
  }
  for (const c of doc.egfr_cases) {
    let got;
    try {
      const v = c.equation === 'cr' ? KF.egfrCr(c.creatinine, c.age, c.sex)
        : c.equation === 'cr_cys' ? KF.egfrCrCys(c.creatinine, c.cystatin_c, c.age, c.sex) : KF.egfrCys(c.cystatin_c, c.age, c.sex);
      got = { unrounded: v, rounded: KF.roundEgfr(v), category: KF.gfrCategory(v) };
    } catch (e) { got = e instanceof KF.KidneyFunctionError ? { error: e.message } : { exception: String(e) }; }
    const label = `egfr ${c.equation} ${JSON.stringify(c)}`;
    if ('unrounded' in c.expect && 'unrounded' in got) {
      checks += 1;
      if (!closeTo(got.unrounded, c.expect.unrounded)) failures.push({ label: `${label}: unrounded`, got: got.unrounded, want: c.expect.unrounded });
      expect(`${label}: rounded`, [got.rounded, got.category], [c.expect.rounded, c.expect.category]);
    } else expect(label, got, c.expect);
  }
  for (const c of doc.category_cases) expect(`gfr_category(${c.egfr})`, KF.gfrCategory(c.egfr), c.category);
  for (const c of doc.albuminuria_cases) expect(`albuminuria_category(${c.value}, ${c.unit})`, KF.albuminuriaCategory(c.value, c.unit), c.category);
  for (const c of doc.age_cases) expect(`age_on(${c.birth_month}, ${c.today}, ${c.last_day})`, KF.ageOn(c.birth_month, c.today, { lastDay: c.last_day }), c.age);
  for (const c of doc.assess_cases) expect(`assess "${c.name}"`, KF.assess({ labs: c.labs, today: c.today, ...c.profile }), c.expect);
  return [checks, failures, `${doc.conversion_cases.length} conversions, ${doc.egfr_cases.length} eGFR cases, ${doc.assess_cases.length} cards`];
}

