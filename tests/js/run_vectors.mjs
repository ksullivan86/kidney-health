// Weights and blood pressure readings from the iPhone Health app's export.xml (read on the device as a stream of text): js/engine/apple_health.js
// has no server twin (the file never reaches the server), so tests/data/apple_health_vectors.json is generated by
// tests/js/gen_apple_health_vectors.mjs from hand-written export.xml fragments and hand-written expectations. Each case is replayed as a list of
// strings cut at every chunk size of the file (and at the case's own cuts), and as a byte stream decoded by TextDecoderStream; the module
// is given the browser's crypto and TextEncoder, which a bare V8 context lacks. This group is async, so main() does not run it.
async function appleHealthVectors() {
  const context = vm.createContext({ console, crypto: globalThis.crypto, TextEncoder });
  for (const rel of APPLE_HEALTH_ENGINE) vm.runInContext(readFileSync(join(ROOT, rel), 'utf8'), context, { filename: rel });
  const A = vm.runInContext('globalThis.KH.appleHealth', context);
  const doc = JSON.parse(readFileSync(APPLE_HEALTH_VECTORS, 'utf8'));
  const failures = [];
  let checks = 0;
  const expect = (label, got, want) => {
    checks += 1;
    if (!isDeepStrictEqual(plain(got), want)) failures.push({ label, got: plain(got), want });
  };
  const sha32 = (text) => createHash('sha256').update(text, 'utf8').digest('hex').slice(0, 32);
  const toHex = (bytes) => Array.from(bytes, (b) => b.toString(16).padStart(2, '0')).join('');
  const expand = (xml) => (typeof xml === 'string' ? xml : xml.map((p) => (typeof p === 'string' ? p : p.repeat.text.repeat(p.repeat.count))).join(''));
  const chunked = (text, size) => {
    if (size === 'whole') return [text];
    const out = [];
    for (let at = 0; at < text.length; at += size) out.push(text.slice(at, at + size));
    return out;
  };
  const byteStream = (text, size, onCancel) => {
    const bytes = new TextEncoder().encode(text);
    let at = 0;
    return new ReadableStream({
      pull(controller) {
        if (at >= bytes.length) { controller.close(); return; }
        controller.enqueue(bytes.subarray(at, at + size));
        at += size;
      },
      cancel() { if (onCancel) onCancel(); },
    }).pipeThrough(new TextDecoderStream());
  };
  const caught = async (fn) => { try { await fn(); return null; } catch (e) { return { name: e && e.name, message: e && e.message }; } };
  const strip = (rows) => rows.map(({ key_input, ...row }) => row);

  expect('limits', {
    max_tag: A.MAX_TAG, batch_size: A.BATCH_SIZE, progress_step: A.PROGRESS_STEP, kg_per_lb: A.KG_PER_LB, ranges: A.RANGES,
    types: { weight: A.TYPE_WEIGHT, systolic: A.TYPE_SYSTOLIC, diastolic: A.TYPE_DIASTOLIC },
  }, doc.limits);

  // The context a clock time gives and what counts as a watch: the server's body.context_for and body.is_watch_source (the phone shortcut's
  // POST /push/v1/body uses them) must answer as this reader does, so a reading gets the same context by either way in
  // (tests/data/body_vectors.json, context_cases and watch_cases, generated from the server's own functions).
  const bodyDoc = JSON.parse(readFileSync(BODY_VECTORS, 'utf8'));
  for (const c of bodyDoc.context_cases) {
    if (c.minutes === null) continue; // "no time" is the server's: the reader always has a time
    expect(`context_for(${c.kind}, ${c.time})`, A.contextOf(c.kind, c.minutes), c.context);
  }
  for (const c of bodyDoc.watch_cases) expect(`is_watch_source(${JSON.stringify(c.name)})`, A.isWatchSource(c.name), c.watch);

  // the cases: each source_key recomputed here from the hand-written key text, then the scan at every chunk size
  let scans = 0;
  for (const c of doc.cases) {
    const text = c.chunks ? c.chunks.join('') : expand(c.xml);
    for (const row of [...c.expected.weights, ...c.expected.readings]) expect(`${c.name}: source_key of ${JSON.stringify(row.key_input)}`, sha32(row.key_input), row.source_key);
    const want = { weights: strip(c.expected.weights), readings: strip(c.expected.readings), summary: c.expected.summary };
    const runs = doc.chunk_sizes.map((size) => [`chunks of ${size}`, chunked(text, size)]);
    if (c.chunks) runs.push(['the case\'s own chunks', c.chunks]);
    for (const [label, chunks] of runs) {
      const got = await A.scan(chunks, c.options);
      scans += 1;
      expect(`${c.name} (${label})`, { weights: got.weights, readings: got.readings, summary: got.summary }, want);
      expect(`${c.name} (${label}): the carry-over buffer stays within ${doc.limits.max_tag}`, got.stats.maxCarry <= doc.limits.max_tag, true);
      expect(`${c.name} (${label}): every character was read`, got.stats.chars, text.length);
    }
  }
  // a stream of bytes decoded by TextDecoderStream, cut where it falls inside a multi-byte character; an async iterable; one string
  for (const c of doc.cases.filter((x) => /Basic Multilingual|split a tag start|decoded, once|Windows line/.test(x.name))) {
    const text = c.chunks ? c.chunks.join('') : expand(c.xml);
    const want = { weights: strip(c.expected.weights), readings: strip(c.expected.readings), summary: c.expected.summary };
    const sources = [
      ...[1, 5, 64].map((n) => [`a byte stream in pieces of ${n} bytes`, () => byteStream(text, n)]),
      ['an async iterable', () => (async function* gen() { for (const part of chunked(text, 11)) yield part; })()],
      ['one string', () => text],
    ];
    for (const [label, make] of sources) {
      const got = await A.scan(make(), c.options);
      expect(`${c.name} (${label})`, { weights: got.weights, readings: got.readings, summary: got.summary }, want);
    }
  }

  // the option and error paths of scan()
  const text = '<Record type="HKQuantityTypeIdentifierBodyMass" sourceName="Health" unit="kg" startDate="2026-10-19 07:15:00 -0400" value="70.5"/>';
  expect('a Uint8Array chunk is refused', await caught(() => A.scan([new Uint8Array(3)])),
    { name: 'TypeError', message: 'The Apple Health reader takes text: pipe the file stream through TextDecoderStream, or pass strings.' });
  let cancelledBytes = false;
  const bytesOnly = new ReadableStream({ pull(controller) { controller.enqueue(new Uint8Array(3)); }, cancel() { cancelledBytes = true; } });
  expect('a stream of bytes is refused and cancelled', [await caught(() => A.scan(bytesOnly)), cancelledBytes, bytesOnly.locked],
    [{ name: 'TypeError', message: 'The Apple Health reader takes text: pipe the file stream through TextDecoderStream, or pass strings.' }, true, false]);
  expect('a number is not a source', (await caught(() => A.scan(42))).name, 'TypeError');
  expect('today must be a real day', [await caught(() => A.scan('', { today: '2026-02-30' })), await caught(() => A.scan('', { today: 'today' }))].map((e) => e.name), ['TypeError', 'TypeError']);
  let cancelled = false;
  let sent = 0;
  const controller = new AbortController();
  const aborting = new ReadableStream({
    pull(c) {
      sent += 1;
      if (sent === 3) controller.abort();
      c.enqueue(text);
    },
    cancel() { cancelled = true; },
  });
  expect('aborting stops after the chunk being read and cancels the stream', [(await caught(() => A.scan(aborting, { signal: controller.signal }))).name, cancelled, aborting.locked],
    ['AbortError', true, false]);
  let preCancelled = false;
  const unread = new ReadableStream({ cancel() { preCancelled = true; } });
  const already = new AbortController();
  already.abort();
  expect('a signal that is already aborted reads nothing and cancels the stream', [(await caught(() => A.scan(unread, { signal: already.signal }))).name, preCancelled], ['AbortError', true]);
  const calls = [];
  const sixty = 'x'.repeat(60);
  await A.scan([sixty, sixty, sixty, sixty, sixty], { progressEvery: 100, onProgress: (p) => calls.push(p.chars) });
  expect('onProgress is called every progressEvery characters', calls, [120, 240]);
  const stream = byteStream(text, 16);
  const done = await A.scan(stream);
  expect('a finished stream is released', [stream.locked, done.summary.kept.weights], [false, 1]);

  // the review sheet's helpers
  for (const c of doc.default_since) expect(`defaultSince(${c.today})`, A.defaultSince(c.today), c.since);
  for (const bad of doc.default_since_errors) expect(`defaultSince(${JSON.stringify(bad)}) is refused`, (await caught(() => A.defaultSince(bad))).name, 'TypeError');
  const days = ['2026-07-20', '2026-07-21', '2026-07-22', '2026-07-23', '2026-10-22'];
  for (const c of doc.filter_since) expect(`filterSince: ${c.name}`, A.filterSince(days.map((date) => ({ date })), c.since).map((r) => r.date), c.expected);
  for (const bad of doc.filter_since_errors) expect(`filterSince(${JSON.stringify(bad)}) is refused`, (await caught(() => A.filterSince([], bad))).name, 'TypeError');
  const rowsOf = (n) => Array.from({ length: n }, (_, i) => ({ date: '2026-01-01', n: i }));
  for (const c of doc.batches) {
    const groups = A.batches(rowsOf(c.count), c.size);
    expect(`batches of ${c.size} for ${c.count} rows`, groups.map((g) => g.length), c.sizes);
    expect(`batches of ${c.size} for ${c.count} rows keep the order`, groups.flat().map((r) => r.n), rowsOf(c.count).map((r) => r.n));
  }
  expect('batches default to 1,000 rows', A.batches(rowsOf(2500)).map((g) => g.length), [1000, 1000, 500]);
  for (const bad of doc.batch_errors) expect(`batches(size ${JSON.stringify(bad)}) is refused`, (await caught(() => A.batches([], bad))).name, 'RangeError');
  for (const [name, want] of doc.watch) expect(`isWatchSource(${JSON.stringify(name)})`, A.isWatchSource(name), want);
  for (const c of doc.upload) expect('forUpload drops the source name and nothing else', A.forUpload([c.row]), [c.expected]);

  // SHA-256: crypto.subtle and the plain-JavaScript fallback give the digests the FIPS examples give, and agree with node:crypto on every
  // length around the block boundaries and on every key text of the cases
  const encoder = new TextEncoder();
  for (const s of doc.sha256) {
    const input = s.repeat ? s.repeat.text.repeat(s.repeat.count) : s.text;
    expect(`SHA-256 (subtle) of ${s.name}`, (await A.sha256Hex(input)).slice(0, s.digest.length), s.digest);
    expect(`SHA-256 (plain JavaScript) of ${s.name}`, toHex(A.sha256Js(encoder.encode(input))).slice(0, s.digest.length), s.digest);
  }
  for (let n = 0; n <= 200; n += 1) {
    const input = 'abé€😀'.repeat(40).slice(0, n);
    const expected = createHash('sha256').update(input, 'utf8').digest('hex');
    expect(`SHA-256 (plain JavaScript) of ${n} characters`, toHex(A.sha256Js(encoder.encode(input))), expected);
  }
  for (const c of doc.cases) {
    for (const row of [...c.expected.weights, ...c.expected.readings]) {
      expect(`SHA-256 (plain JavaScript) of ${JSON.stringify(row.key_input)}`, toHex(A.sha256Js(encoder.encode(row.key_input))).slice(0, 32), row.source_key);
    }
  }
  // without crypto.subtle (a page served over plain HTTP) the scan gives the same keys
  const plainContext = vm.createContext({ console, TextEncoder });
  plainContext.window = plainContext; // and as a page has it: the script finds `window` first
  for (const rel of APPLE_HEALTH_ENGINE) vm.runInContext(readFileSync(join(ROOT, rel), 'utf8'), plainContext, { filename: rel });
  const P = vm.runInContext('globalThis.KH.appleHealth', plainContext);
  const fromJs = await P.scan(text);
  const fromSubtle = await A.scan(text);
  expect('without crypto.subtle the source_key is the same', plain(fromJs.weights), plain(fromSubtle.weights));
  return [checks, failures, `${doc.cases.length} files x ${doc.chunk_sizes.length} chunk sizes (${scans} scans), ${doc.default_since.length} periods, ${doc.sha256.length} digests`];
}

function report(name, file, [checks, failures, summary]) {
  if (failures.length) {
    for (const f of failures.slice(0, 20)) console.error(`MISMATCH ${f.label}\n   js:     ${JSON.stringify(f.got)}\n   python: ${JSON.stringify(f.want)}`);
    console.error(`\n${failures.length} of ${checks} checks failed (${file})`);
    return 1;
  }
  console.log(`${name} vectors: ${checks} checks passed (${summary})`);
  return 0;
}

