function loadEngine() {
  const context = vm.createContext({ console });
  for (const rel of ENGINE) vm.runInContext(readFileSync(join(ROOT, rel), 'utf8'), context, { filename: rel });
  const KH = vm.runInContext('globalThis.KH', context);
  if (!KH || !KH.rules) throw new Error('rules.js did not define KH.rules');
  return KH.rules;
}

// Values cross the V8 context boundary; compare plain JSON copies.
const plain = (v) => JSON.parse(JSON.stringify(v));
// The same, keeping the sign of zero: Python writes -0.0 (for example a delta of -0.04 g rounded to one decimal),
// JSON.parse reads it as -0, and isDeepStrictEqual tells -0 from 0.
const NEG_ZERO = '\u0000-0';
const plainSigned = (v) => JSON.parse(JSON.stringify(v, (k, x) => (Object.is(x, -0) ? NEG_ZERO : x)), (k, x) => (x === NEG_ZERO ? -0 : x));

