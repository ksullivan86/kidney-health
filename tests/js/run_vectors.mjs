#!/usr/bin/env node
// Parity check of the browser twins against the server (ARCHITECTURE.md, "Frontend modules").
//
//   node tests/js/run_vectors.mjs            # exit 0 when every vector matches, 1 otherwise
//   node tests/js/run_vectors.mjs --guidance FILE   # replay only a guidance vector file (same format as
//                                                   # tests/data/guidance_vectors.json, e.g. a fuzz run)
//
// 1. Rules: app/static/js/engine/rules.js against tests/data/rules_vectors.json (app/nutrients.py).
// 2. Settings: app/static/js/engine/settings.js against tests/data/settings_vectors.json
//    (app/settings_registry.py + app/settings_store.py, generated by tests/data/gen_settings_vectors.py):
//    the registry table, value validation, and the precedence views of GET /api/me/settings and
//    GET /api/admin/settings, which the Settings view and the demo API (js/mock/settings.js) use.
//
// 3. Targets: app/static/js/engine/targets.js against tests/data/targets_vectors.json (app/targets.py +
//    app/target_rules.py, generated by tests/data/gen_targets_vectors.py): the rule tables, reference
//    weight, energy equation, every suggestion case (notes word for word) and the v0.2 wrapper.
// 4. Kidney function: app/static/js/engine/kidney_function.js against tests/data/kidney_function_vectors.json
//    (app/units.py + app/kidney_function.py): units, conversions, eGFR, categories, ages and the card.
// 5. Guidance: app/static/js/engine/guidance/*.js against tests/data/guidance_vectors.json (app/guidance/,
//    generated by tests/data/gen_guidance_vectors.py): the rules version and hash, then every case (meal room,
//    what fits now, swaps, low-treatment options, plan-day, day and period insights, the AI prefilter) replayed
//    from the same plain-JSON inputs and compared with the engine's answer exactly, explain blocks included.
// 6. Barcodes: app/static/js/engine/{gtin,textclean,additives,off}.js against tests/data/barcode_vectors.json
//    (app/gtin.py, app/textclean.py, app/additives.py, app/off.py; tests/data/gen_barcode_vectors.py), and the
//    demo's POST /api/foods/barcode (js/mock/barcode.js over js/mock/core.js + foods.js) rebuilding the
//    server's answer for each of its three recorded Open Food Facts products.
// 7. Lab import: app/static/js/engine/lab_import.js against tests/data/lab_import_vectors.json (v0.3.1; generated by
//    tests/js/gen_lab_import_vectors.mjs, reviewed by hand: the reader has no Python twin because the file never
//    reaches the server; tests/test_lab_import.py checks its conversions against app/units.py).
// 7b. Apple Health clinical records: app/static/js/engine/fhir_labs.js against tests/data/fhir_labs_vectors.json (generated by
//    tests/js/gen_fhir_labs_vectors.mjs from hand-written FHIR resources and hand-written expectations; read in the browser, so
//    no server twin; tests/test_fhir_labs.py checks every LOINC code's test and unit against app/units.py).
// 7c. Patient-portal C-CDA files: app/static/js/engine/ccda_labs.js against tests/data/ccda_labs_vectors.json (generated by
//    tests/js/gen_ccda_labs_vectors.mjs from hand-written C-CDA documents and hand-written expectations; the XML is parsed in the
//    browser, so no server twin; Node has no DOMParser, so the dev-only tests/js/mini_xml.mjs is handed to the engine as `parseXml`;
//    tests/test_ccda_labs.py checks every converted value against app/units.py).
// 8. Menu link: app/static/js/engine/menu_link.js against tests/data/menu_link_vectors.json (v0.4; written by hand: the
//    handbook's "Add this day to my plan" link is read in the browser, which looks every food up in the app's own
//    built-in list, so there is no server twin; tests/test_menu_plan.py runs it over every generated link).
//
// 9. Symptoms: app/static/js/engine/symptoms.js and the demo's /api/symptoms routes (js/mock/symptoms.js) against
//    tests/data/symptoms_vectors.json (app/symptoms.py + the SymptomCreate model, generated by
//    tests/data/gen_symptoms_vectors.py): the list, severities, limits and handbook red flags, the API shape of a row,
//    one request script (every route, every refusal and its text) replayed on a fresh demo, the Trends grouping, and
//    that a symptom of another person is invisible and a 404.
//
// 10. Entry versions (offline edits and deletes): the demo's `entryVersion` / `versionMatches` and its PUT / DELETE
//    /api/log/{id} with If-Match (js/mock/log.js) against tests/data/entry_version_vectors.json (app/log.py, generated by
//    tests/data/gen_entry_version_vectors.py): the hash of entries' content, If-Match headers, and one request script
//    (a match, a 412 with the current entry, no header, a star, a list, a weak tag, a bad body, a missing entry,
//    deletes) replayed on a fresh demo.
//
// 11. Import of export.json ("Keep my data in this browser"): the demo's POST /api/me/import (js/mock/import.js) against
//    tests/data/import_vectors.json (app/data_import.py, generated by tests/data/gen_import_vectors.py): the fixed texts, then one
//    request script replayed on a fresh, empty demo with the real built-in food list: every refusal in its words (a file that is not
//    an export, a version, the depth limit, an unknown field, a field of the wrong kind or out of range, a food id used twice, a list
//    over its limit, the profile and the settings), the dry run, the account that already has data, the import with and without the
//    profile, adding the same file again, an older file, and what the account holds afterwards (ids and times left out).
//
