"""Vectors of ``POST /push/v1/body`` for a native client (design note 15 §4.1).

``tests/data/push_vectors.json`` is generated by ``tests/data/gen_push_vectors.py`` from the route's own code (``app/push.py``) and
replayed by the Swift package ``ios/KidneyHealthCore`` (``swift test``). These tests fail when the committed file no longer matches
the route, and check what the vectors cover.
"""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path

import pytest

from app import push as P

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "tests" / "data"


def generator():
    spec = importlib.util.spec_from_file_location("gen_push_vectors", DATA / "gen_push_vectors.py")
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def committed():
    return json.loads((DATA / "push_vectors.json").read_text(encoding="utf-8"))


def test_vectors_are_current(committed):
    assert committed == generator().build(), (
        "tests/data/push_vectors.json is stale: app/push.py or a body rule changed. Run "
        "`python3 tests/data/gen_push_vectors.py`, then `swift test --package-path ios/KidneyHealthCore`, and update the Swift "
        "package (ios/KidneyHealthCore) until both agree."
    )


def test_the_limits_are_the_routes(committed):
    k = committed["constants"]
    assert k["path"] == "/push/v1/body" and k["max_rows"] == P.MAX_ROWS == 50 and k["max_source_chars"] == 60
    assert k["kg"] == [20, 400] and k["systolic"] == [50, 300] and k["diastolic"] == [20, 200]


def test_the_vectors_cover_each_refusal_and_the_watch_rule(committed):
    weights = {c.get("refused") for c in committed["weight_cases"]}
    readings = {c.get("refused") for c in committed["reading_cases"]}
    assert {None, "at", "value", "source"} <= weights
    assert {None, "at", "systolic", "diastolic", "source"} <= readings
    watch = [c["planned"]["watch"] for c in committed["reading_cases"] if "planned" in c]
    assert True in watch and False in watch
    assert any(c["row"]["unit"] == "lb" and "planned" in c for c in committed["weight_cases"])
    assert any(c["text"] is None for c in committed["value_cases"])
    assert any(c["kept"] is None for c in committed["source_cases"])


def test_the_clock_cases_cross_daylight_saving_changes(committed):
    offsets = {(c["zone"], c["at"][-6:]) for c in committed["clock_cases"]}
    assert ("America/New_York", "-05:00") in offsets and ("America/New_York", "-04:00") in offsets
    assert ("Asia/Kathmandu", "+05:45") in offsets
    for case in committed["clock_cases"]:
        assert P.parse_at(case["at"]).stamp == case["stamp"]
