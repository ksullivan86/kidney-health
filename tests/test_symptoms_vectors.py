"""Parity vectors for the browser twin of the symptoms log (ARCHITECTURE.md "Symptoms log", "Frontend modules").

``tests/data/symptoms_vectors.json`` is generated by ``tests/data/gen_symptoms_vectors.py`` from the server's own code
(``app/symptoms.py``, the ``SymptomCreate`` model) and replayed by ``node tests/js/run_vectors.mjs`` against
``app/static/js/engine/symptoms.js`` and the demo API ``app/static/js/mock/symptoms.js``. These tests fail when the
committed file no longer matches the server (regenerate it, then make the twin agree), and check what the vectors cover.
"""
from __future__ import annotations

import importlib.util
import json
import shutil
import subprocess
from pathlib import Path

import pytest

from app import symptoms as S
from app.models import MAX_SYMPTOMS_PER_DAY

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "tests" / "data"


def generator():
    spec = importlib.util.spec_from_file_location("gen_symptoms_vectors", DATA / "gen_symptoms_vectors.py")
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def committed():
    return json.loads((DATA / "symptoms_vectors.json").read_text(encoding="utf-8"))


def test_vectors_are_current(committed):
    fresh = generator().build()
    assert committed == fresh, (
        "tests/data/symptoms_vectors.json is stale: app/symptoms.py or the SymptomCreate model changed. Run "
        "`python3 tests/data/gen_symptoms_vectors.py`, then `node tests/js/run_vectors.mjs`, and update the browser twin "
        "(app/static/js/engine/symptoms.js, app/static/js/mock/symptoms.js) until both agree."
    )


def test_the_tables_in_the_vectors_are_the_servers(committed):
    assert committed["symptoms"] == [list(item) for item in S.SYMPTOMS]
    assert committed["red_flags"] == {k: {"level": e["level"], "text": e["text"]} for k, e in S.RED_FLAGS.items()}
    assert committed["href"] == S.GET_HELP_NOW_HREF == "/learn/get-help-now/"
    assert committed["limits"]["max_per_day"] == MAX_SYMPTOMS_PER_DAY


def test_the_vectors_cover_every_route_and_refusal(committed):
    script = committed["script"]
    seen = {(s["method"], s["path"].split("?")[0].rstrip("0123456789").rstrip("/")) for s in script}
    assert {("GET", "/api/symptoms"), ("POST", "/api/symptoms"), ("PUT", "/api/symptoms"), ("DELETE", "/api/symptoms")} <= seen
    statuses = {s["answer"]["status"] for s in script if not s["answer"]["ok"]}
    assert statuses == {400, 404}
    details = " | ".join(s["answer"]["detail"] for s in script if not s["answer"]["ok"])
    for fragment in ("Extra inputs are not permitted", "Field required", "must not be in the future", "must be 1900 or later",
                     "label is required when the symptom is other", "label is only for the symptom other", "must be plain text",
                     "must be one line of plain text", "too many symptoms for one day", "range too large", "Symptom not found",
                     "symptom_id: Input should be a valid integer", "Input should be greater than or equal to 1",
                     "Input should be less than or equal to 3", "Input should be a valid dictionary or object"):
        assert fragment in details, fragment
    created = [s for s in script if s["method"] == "POST" and s["answer"]["ok"]]
    assert {s["answer"]["body"]["symptom"] for s in created} >= {"swelling", "breathlessness", "tiredness", "other", "itching", "nausea",
                                                              "poor_appetite", "cramps"}
    assert any(s["answer"]["body"]["red_flag"] and s["answer"]["body"]["red_flag"]["prominent"] for s in created)
    assert any(s["answer"]["body"]["red_flag"] and not s["answer"]["body"]["red_flag"]["prominent"] for s in created)
    assert any("{{today:2}}" in json.dumps(s.get("body")) and not s["answer"]["ok"] for s in script)  # the clock-dependent boundary
    rows = {(c["row"]["symptom"], c["row"]["severity"]) for c in committed["row_cases"]}
    assert rows >= {(key, sev) for key, _ in S.SYMPTOMS for sev in (1, 2, 3)}


def test_the_node_runner_replays_the_symptoms_vectors():
    assert shutil.which("node"), "Node.js 22 is needed for the JS parity vectors (CLAUDE.md, Parity): install it and run again"
    proc = subprocess.run(["node", str(ROOT / "tests" / "js" / "run_vectors.mjs")], capture_output=True, text=True, timeout=120)
    assert proc.returncode == 0, proc.stdout + proc.stderr
    assert "symptoms vectors:" in proc.stdout and "checks passed" in proc.stdout
