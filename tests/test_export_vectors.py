"""The export .zip built in the page (the iPhone app with no server, and "Keep my data in this browser").

``tests/data/export_vectors.json`` is generated by ``tests/data/gen_export_vectors.py`` from the server's own archive
(``app/account.py`` ``build_export`` behind ``GET /api/me/export.zip``) and replayed by ``node tests/js/export_vectors.mjs``
against the twin in ``app/static/js/mock/export.js`` (``M.exportZip``). These tests fail when the committed file no longer
matches the server, check that the twin's fixed lists are the server's, and run the Node check.
"""
from __future__ import annotations

import importlib.util
import json
import re
import shutil
import subprocess
from pathlib import Path

import pytest

from app import account, activity, body, brand, labs, log, symptoms
from app.nutrients import NUTRIENT_KEYS

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "tests" / "data"
EXPORT_JS = (ROOT / "app" / "static" / "js" / "mock" / "export.js").read_text(encoding="utf-8")
DEMO_LOCAL_JS = (ROOT / "app" / "static" / "js" / "views" / "demo_local.js").read_text(encoding="utf-8")


def generator():
    spec = importlib.util.spec_from_file_location("gen_export_vectors", DATA / "gen_export_vectors.py")
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def committed():
    return json.loads((DATA / "export_vectors.json").read_text(encoding="utf-8"))


def test_vectors_are_current(committed):
    fresh = generator().build()
    for key in ("names", "files", "food_sources", "readme_brand", "filename", "filename_cases"):
        assert committed[key] == fresh[key], (
            f"tests/data/export_vectors.json ({key}) is stale: app/account.py build_export changed. Run "
            "`python3 tests/data/gen_export_vectors.py`, then `node tests/js/export_vectors.mjs`, and update the twin in "
            "app/static/js/mock/export.js until both agree."
        )


def test_the_vectors_test_the_writer(committed):
    files = committed["files"]
    assert files["README.txt"] == account.README
    every = "".join(files.values())
    for needle in ('""', "\n", "'=", "'+", "'-", "'@", "True", "False", "5.0", "Crème"):
        assert needle in every, needle
    assert all(text.endswith("\r\n") for name, text in files.items() if name.endswith(".csv"))
    assert all(len(text.split("\r\n")) > 2 for name, text in files.items() if name.endswith(".csv")), "every CSV file has a row"


def js_list(name: str) -> list[str]:
    found = re.search(rf"const {name} = \[([^\]]*)\]", EXPORT_JS)
    assert found, name
    return [json.loads(f'"{s}"') for s in re.findall(r"'((?:[^'\\]|\\.)*)'", found.group(1))]


def test_the_columns_and_prefixes_in_the_twin_are_the_servers():
    assert js_list("FOOD_FIELDS") == list(account.FOOD_CSV_FIELDS)
    assert js_list("LAB_COLUMNS") == list(labs.CSV_COLUMNS)
    assert js_list("SYMPTOM_COLUMNS") == list(symptoms.CSV_COLUMNS)
    assert js_list("WEIGHT_COLUMNS") == list(body.WEIGHT_CSV_COLUMNS)
    assert js_list("READING_COLUMNS") == list(body.READING_CSV_COLUMNS)
    assert js_list("DAY_COLUMNS") == list(activity.DAY_COLUMNS)
    assert js_list("WORKOUT_COLUMNS") == list(activity.WORKOUT_COLUMNS)
    assert js_list("FORMULA_PREFIXES") == list(log._FORMULA_PREFIXES)
    assert list(log.CSV_COLUMNS)[9:9 + len(NUTRIENT_KEYS)] == list(NUTRIENT_KEYS)
    assert brand.SLUG == "kidney-health"


def test_the_page_downloads_the_zip():
    assert "api._exportArchive()" in DEMO_LOCAL_JS and "application/zip" in DEMO_LOCAL_JS
    assert "export.json'" not in DEMO_LOCAL_JS.split("function exportFile")[1].split("function init")[0]


@pytest.mark.skipif(shutil.which("node") is None, reason="needs node")
def test_the_twin_rebuilds_the_servers_files():
    result = subprocess.run(["node", str(ROOT / "tests" / "js" / "export_vectors.mjs")], capture_output=True, text=True, timeout=120)
    assert result.returncode == 0, result.stdout + result.stderr
    assert "checks passed" in result.stdout
