"""Parity vectors for the browser twin of the weight and blood pressure log (ARCHITECTURE.md "Weight and blood pressure", "Frontend modules").

``tests/data/body_vectors.json`` is generated by ``tests/data/gen_body_vectors.py`` from the server's own code (``app/body.py``, the
models of ``app/models.py``) and replayed by ``node tests/js/run_vectors.mjs`` against ``app/static/js/engine/body.js`` and the demo
API ``app/static/js/mock/body.js``. These tests fail when the committed file no longer matches the server (regenerate it, then
make the twin agree), and check what the vectors cover.
"""
from __future__ import annotations

import importlib.util
import json
import re
import shutil
import subprocess
from pathlib import Path

import pytest

from app import body as B
from app import models

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "tests" / "data"


def generator():
    spec = importlib.util.spec_from_file_location("gen_body_vectors", DATA / "gen_body_vectors.py")
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def committed():
    return json.loads((DATA / "body_vectors.json").read_text(encoding="utf-8"))


def test_vectors_are_current(committed):
    fresh = generator().build()
    assert committed == fresh, (
        "tests/data/body_vectors.json is stale: app/body.py or a body model changed. Run "
        "`python3 tests/data/gen_body_vectors.py`, then `node tests/js/run_vectors.mjs`, and update the browser twin "
        "(app/static/js/engine/body.js, app/static/js/mock/body.js) until both agree."
    )


def test_the_tables_in_the_vectors_are_the_servers(committed):
    k = committed["constants"]
    assert k["kg_per_lb"] == B.KG_PER_LB == 0.45359237
    assert k["weight_contexts"] == list(B.WEIGHT_CONTEXTS) and k["blood_pressure_contexts"] == list(B.BLOOD_PRESSURE_CONTEXTS)
    assert k["limits"]["max_weights_per_day"] == models.MAX_WEIGHTS_PER_DAY == 20
    assert k["limits"]["max_readings_per_day"] == models.MAX_READINGS_PER_DAY == 30
    assert k["limits"]["max_batch"] == models.MAX_BODY_BATCH == 1000
    assert k["red_flags"] == {key: {"level": e["level"], "text": e["text"], "prominent": e["prominent"]} for key, e in B.RED_FLAGS.items()}
    assert k["href"] == "/learn/get-help-now/" and (k["flag_systolic"], k["flag_diastolic"]) == (180, 120)


def test_the_vectors_cover_every_route_and_refusal(committed):
    script = committed["script"]
    seen = {(s["method"], re.sub(r"/\d+$", "", s["path"].split("?")[0])) for s in script if s["path"].startswith("/api/body")}
    expected = {("GET", "/api/body/weights"), ("POST", "/api/body/weights"), ("PUT", "/api/body/weights"), ("DELETE", "/api/body/weights"),
                ("POST", "/api/body/weights/batch"), ("GET", "/api/body/blood-pressure"), ("POST", "/api/body/blood-pressure"),
                ("PUT", "/api/body/blood-pressure"), ("DELETE", "/api/body/blood-pressure"), ("POST", "/api/body/blood-pressure/batch"),
                ("GET", "/api/body/summary")}
    assert expected <= seen, sorted(expected - seen)
    statuses = {s["answer"]["status"] for s in script if not s["answer"]["ok"]}
    assert statuses == {400, 404}
    details = " | ".join(s["answer"]["detail"] for s in script if not s["answer"]["ok"])
    for fragment in ("Extra inputs are not permitted", "Field required", "must not be in the future", "must be 1900 or later",
                     "systolic must be greater than diastolic", "must be plain text", "must be a time such as 07:30",
                     "too many weights for one day", "too many blood pressure readings for one day", "range too large",
                     "Weight not found", "Blood pressure reading not found", "weight_id: Input should be a valid integer",
                     "reading_id: Input should be a valid integer", "Input should be greater than or equal to 20",
                     "Input should be less than or equal to 400", "Input should be a finite number", "rows.1.", "rows.0:",
                     "List should have at least 1 item", "List should have at most 1000 items", "Input should be a valid dictionary",
                     "must be one line of plain text", "body.weight_alarm:", "body.bp_goal:", "user.units.weight:", "date is required"):
        assert fragment in details, fragment
    created = [s for s in script if s["method"] == "POST" and s["answer"]["ok"] and isinstance(s["answer"].get("body"), dict)
               and "id" in s["answer"]["body"]]
    assert {s["answer"]["body"]["context"] for s in created} >= {"morning", "other", "before_dialysis", "after_dialysis", "evening"}
    flags = [s["answer"]["body"]["flag"] for s in created if "systolic" in s["answer"]["body"]]
    assert any(f and f["prominent"] for f in flags) and any(f is None for f in flags)
    assert any("{{today:2}}" in json.dumps(s.get("body")) and not s["answer"]["ok"] for s in script)  # the clock-dependent boundary
    alarms = [s["answer"]["body"]["weight"]["alarm"] for s in script if s["path"].startswith("/api/body/summary") and s["answer"]["ok"]
              and s["answer"]["body"]["weight"]["alarm"]]
    assert {a["status"] for a in alarms} == {"compared", "no_reference"} and {a["reference_kind"] for a in alarms} >= {"same_context", "dry_weight", "after_dialysis"}
    assert any(a["over_alarm"] for a in alarms) and any(a["over_alarm"] is False for a in alarms)


def test_the_vectors_cover_the_pure_functions(committed):
    assert {c["name"].split(":")[0] for c in committed["alarm_cases"]} == {"days", "between sessions", "no alarm number", "no weights", "no weights, between sessions"}
    assert any(c["expected"] and c["expected"]["over_alarm"] for c in committed["alarm_cases"])
    assert any(c["expected"] is None for c in committed["alarm_cases"])
    assert {(c["systolic"], c["diastolic"], c["flag"] is not None) for c in committed["flag_cases"]} >= {(179, 119, False), (180, 80, True), (140, 120, True)}
    assert any(c["expected"] is None for c in committed["six_month_cases"]) and any(c["expected"] for c in committed["six_month_cases"])
    assert any(c["expected"]["few"] for c in committed["week_cases"]) and any(not c["expected"]["few"] for c in committed["week_cases"])
    assert {r["kind"] for r in committed["row_cases"]} == {"weight", "reading"}


def test_the_node_runner_replays_the_body_vectors():
    assert shutil.which("node"), "Node.js 22 is needed for the JS parity vectors (CLAUDE.md, Parity): install it and run again"
    proc = subprocess.run(["node", str(ROOT / "tests" / "js" / "run_vectors.mjs")], capture_output=True, text=True, timeout=180)
    assert proc.returncode == 0, proc.stdout + proc.stderr
    assert "body vectors:" in proc.stdout and "checks passed" in proc.stdout
