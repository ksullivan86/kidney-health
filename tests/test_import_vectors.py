"""Parity vectors for the browser twin of the export.json import (ARCHITECTURE.md "Keep my data in this browser").

``tests/data/import_vectors.json`` is generated by ``tests/data/gen_import_vectors.py`` from the server's own code
(``app/data_import.py`` behind ``POST /api/me/import``) and replayed by ``node tests/js/run_vectors.mjs`` against the demo API
(``app/static/js/mock/import.js``). These tests fail when the committed file no longer matches the server (regenerate it, then
make the twin agree), check that the limits written in the twin are the server's, and check what the vectors cover.
"""
from __future__ import annotations

import importlib.util
import json
import re
import shutil
import subprocess
from pathlib import Path

import pytest

from app import data_import
from app.config import Settings
from app.guidance.context import MAX_NOT_FOR_ME

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "tests" / "data"
IMPORT_JS = (ROOT / "app" / "static" / "js" / "mock" / "import.js").read_text(encoding="utf-8")


def generator():
    spec = importlib.util.spec_from_file_location("gen_import_vectors", DATA / "gen_import_vectors.py")
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def committed():
    return json.loads((DATA / "import_vectors.json").read_text(encoding="utf-8"))


def test_vectors_are_current(committed):
    fresh = generator().build()
    assert committed == fresh, (
        "tests/data/import_vectors.json is stale: app/data_import.py (or what it validates with) changed. Run "
        "`python3 tests/data/gen_import_vectors.py`, then `node tests/js/run_vectors.mjs`, and update the browser twin "
        "(app/static/js/mock/import.js) until both agree."
    )


def js_number(name: str) -> int:
    match = re.search(rf"\b{name} = (\d+(?: \* \d+)*)\b", IMPORT_JS)
    assert match, f"{name} is not defined in mock/import.js"
    result = 1
    for part in match.group(1).split(" * "):
        result *= int(part)
    return result


def test_the_limits_in_the_twin_are_the_servers():
    for name in ("MAX_ENTRIES", "MAX_CUSTOM_FOODS", "MAX_LINKED_FOODS", "MAX_BUILTIN_REFS", "MAX_MEALS", "MAX_MEAL_ITEMS", "MAX_LABS", "MAX_SYMPTOMS",
                 "MAX_SETTINGS", "MAX_SKIPPED_SHOWN", "MAX_MESSAGE_CHARS", "MAX_NOTE_CHARS", "MAX_DEPTH"):
        assert js_number(name) == getattr(data_import, name), name
    assert js_number("MAX_NOT_FOR_ME") == MAX_NOT_FOR_ME
    assert js_number("MAX_IMPORT_BYTES") == Settings.__dataclass_fields__["max_import_bytes"].default
    for name in ("IMPORTED_SETTINGS", "SKIPPED_SECTIONS"):
        listed = re.search(rf"const {name} = \[([^\]]*)\]", IMPORT_JS)
        assert listed and re.findall(r"'([^']+)'", listed.group(1)) == list(getattr(data_import, name)), name


def test_the_fixed_texts_are_the_servers(committed):
    constants = committed["constants"]
    assert constants["rule"] == data_import.RULE
    assert constants["not_imported"] == list(data_import.NOT_IMPORTED)
    assert constants["imported_settings"] == list(data_import.IMPORTED_SETTINGS)
    assert constants["skipped_sections"] == list(data_import.SKIPPED_SECTIONS)
    assert constants["max_depth"] == data_import.MAX_DEPTH == 32


def by_name(committed):
    return {step["name"]: step for step in committed["script"]}


def test_the_vectors_cover_every_kind_of_record_and_every_kind_of_refusal(committed):
    steps = by_name(committed)
    statuses = {step["answer"]["status"] for step in committed["script"]}
    assert statuses == {200, 400, 409}
    refused = [step for step in committed["script"] if step["answer"]["status"] == 400 and "kind" in step["answer"]["body"]]
    kinds = {step["answer"]["body"]["kind"] for step in refused}
    assert kinds >= {"log_entries", "custom_foods", "linked_foods", "builtin_foods", "meal_templates", "lab_results", "symptoms",
                     "food_preferences", "profile", "settings", "exported_at", "app_version", "colour"}
    details = " | ".join(step["answer"]["body"].get("detail", "") for step in committed["script"] if step["answer"]["status"] == 400)
    for phrase in ("nested too deeply", "must hold one JSON object", "its \"format\" is not", "this server reads version 1", "unknown field",
                   "Field required", "Input should be a valid", "the same food id is used twice", "List should have at most", "has a nutrient this server does not know",
                   "not a value this server accepts", "a setting name is too long", "must be custom"):
        assert phrase in details, phrase
    # the depth limit: 32 levels are read, 33 are refused
    assert steps["nested 32 deep is read"]["answer"]["status"] == 200 and "nested too deeply" in steps["nested 33 deep"]["answer"]["body"]["detail"]
    # a refusal never repeats what it was sent
    assert "someone" not in details and "secret" not in details


def test_the_vectors_cover_the_flow_and_what_is_never_imported(committed):
    steps = by_name(committed)
    whole = steps["a whole file, as a dry run"]["answer"]["body"]
    assert whole["dry_run"] is True and whole["can_import"] is True and whole["counts"]["log_entries"] == 7
    # nothing but the four allowlisted settings, and only with the profile; the AI setting and a consent are listed as left out
    replacing = steps["a whole file, as a dry run, replacing the profile"]["answer"]["body"]
    assert replacing["counts"]["settings"] == 4 and replacing["counts"]["profile"] == 1
    skipped = {s["label"] for s in replacing["skipped"]["shown"] if s["kind"] == "settings"}
    assert skipped == {"ai", "food.off_consent"}
    assert steps["a whole file, as a dry run"]["answer"]["body"]["not_selected"] == ["your profile and targets", "your meal-guidance and display settings"]
    # the account that has data is refused unless "add to my existing data" is chosen
    assert steps["the account is not empty any more"]["answer"]["body"]["can_import"] is False
    assert steps["the account is not empty: the real import is refused"]["answer"]["status"] == 409
    again = steps["the same file again, imported"]["answer"]["body"]
    assert again["imported"] is True and again["counts"]["log_entries"] == 0 and again["already_there"]["log_entries"] == 7
    # an older file finds built-in foods by id and name, and a food that is nowhere is reported, not guessed
    older = steps["an older file without the list of built-in foods, matched by id and name"]["answer"]["body"]
    assert older["counts"]["log_entries"] == 2 and older["skipped"]["total"] == 1 and older["counts"]["food_preferences"] == 1
    assert "not in the file and is not a built-in food of this server" in older["skipped"]["shown"][0]["reason"]
    # the thirty-first symptom of one day is left out
    assert any("most one day holds" in s["reason"] for s in steps["the whole file imported, with the profile"]["answer"]["body"]["skipped"]["shown"])
    # the saved meal that lost foods says so in its note, for good
    meals = steps["read back: saved meals"]["answer"]["body"]["meals"]
    assert any("Imported without 6 foods that could not be matched" in (m["note"] or "") for m in meals)
    assert not any("secret" in json.dumps(step["answer"]) for step in committed["script"])


def test_the_node_runner_replays_the_import_vectors():
    assert shutil.which("node"), "Node.js 22 is needed for the JS parity vectors (CLAUDE.md, Parity): install it and run again"
    proc = subprocess.run(["node", str(ROOT / "tests" / "js" / "run_vectors.mjs")], capture_output=True, text=True, timeout=300)
    assert proc.returncode == 0, proc.stdout + proc.stderr
    assert "import vectors:" in proc.stdout and "checks passed" in proc.stdout
